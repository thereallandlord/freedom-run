/**
 * Срок действия — В КРУГАХ, а не в зарплатах (просьба Камиля).
 *
 * 🔴 Почему это не просто замена слова. Зарплата приходит ТРИ раза за круг, и
 * «на четыре зарплаты» человеку за столом ничего не говорит: он не знает, когда
 * следующая. Круг он видит глазами — фишка идёт по доске. Поэтому переводим в
 * круги, а точное число зарплат оставляем рядом: механика считает по ним, и
 * врать про это нельзя.
 */
import { RAT_BOARD } from '../engine/data'

/** Сколько зарплат укладывается в один круг. Берём у самой доски, не на глаз. */
export const ЗАРПЛАТ_В_КРУГЕ = Math.max(1, RAT_BOARD.filter((x) => x === 'paycheck').length)

function кругиСлово(n: number): string {
  const сотня = n % 100
  const единица = n % 10
  if (сотня >= 11 && сотня <= 14) return 'кругов'
  if (единица === 1) return 'круг'
  if (единица >= 2 && единица <= 4) return 'круга'
  return 'кругов'
}

/**
 * «примерно полтора круга», «около круга», «два круга».
 * Половинки называем словами: «1,5 круга» на карточке читается как отчёт.
 */
export function вКругах(зарплат: number): string {
  if (зарплат <= 0) return 'до конца этого круга'
  const кругов = зарплат / ЗАРПЛАТ_В_КРУГЕ
  if (кругов < 0.75) return 'меньше круга'
  if (кругов < 1.25) return 'около круга'
  if (кругов < 1.75) return 'примерно полтора круга'
  const целых = Math.round(кругов)
  return `примерно ${целых} ${кругиСлово(целых)}`
}

/** То же, но с точным числом зарплат рядом — там, где важна и механика. */
export function срокПодробно(зарплат: number): string {
  return `${вКругах(зарплат)} (${зарплат} ${зарплатСлово(зарплат)})`
}

function зарплатСлово(n: number): string {
  const сотня = n % 100
  const единица = n % 10
  if (сотня >= 11 && сотня <= 14) return 'зарплат'
  if (единица === 1) return 'зарплата'
  if (единица >= 2 && единица <= 4) return 'зарплаты'
  return 'зарплат'
}
