/**
 * Часы хода: сколько осталось думать.
 *
 * 🔴 ЗАЧЕМ. Три отдельные просьбы с игры: «добавить таймер на принятие решения
 * ~30 секунд», «таймер на ход — просят добавить», «время на ход должно
 * сокращаться с каждым кругом». И причина под ними одна: «игра должна идти
 * быстрее и напряжённее, сейчас слишком много времени на подумать», а те, чей
 * ход не идёт, просто скучают. Камиль добавил: «под таймером начнут вылезать
 * ошибки — это считается плюсом».
 *
 * 🔴 ПОЧЕМУ ЭТО НЕ ЧАСТЬ СТОЛА. Партия пересобирается из журнала ходов, и всё,
 * что в него попадает, обязано быть одинаковым у всех. Настоящее время таким
 * не бывает: у одного вкладка спала, у другого сеть моргнула. Поэтому часы
 * живут в интерфейсе — ровно как часы мировых событий, — а когда время
 * выходит, ход довершает хозяин стола ОБЫЧНЫМ событием. В журнале остаётся
 * то же самое, что было бы при живом нажатии.
 */

let срок = 0
let полный = 0
const слушатели = new Set<() => void>()

/** Сколько секунд даётся на ход. Убывает по кругам, но не ниже минимума. */
export const ХОД_СЕК_СТАРТ = 45
export const ХОД_СЕК_МИН = 20
/** На сколько секунд короче становится ход с каждым пройденным кругом. */
export const ХОД_СЕК_ШАГ = 5

export function срокНаХод(кругов: number): number {
  return Math.max(ХОД_СЕК_МИН, ХОД_СЕК_СТАРТ - кругов * ХОД_СЕК_ШАГ)
}

/** Завести часы на `sec` секунд. Ноль — часы сняты. */
export function завестиЧасыХода(sec: number) {
  срок = sec > 0 ? Date.now() + sec * 1000 : 0
  полный = sec
  for (const n of слушатели) n()
}

/** Срок текущего хода в миллисекундах эпохи. Ноль — часов нет. */
export function срокХода() {
  return срок
}

/** На сколько секунд заведены часы — для полоски. */
export function полныйСрокХода() {
  return полный
}

export function подписатьсяНаЧасыХода(notify: () => void) {
  слушатели.add(notify)
  return () => {
    слушатели.delete(notify)
  }
}
