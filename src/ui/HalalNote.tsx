export function HalalNote({ topic }: { topic: keyof typeof HALAL }) {
  const [open, setOpen] = useState(false)
  const t = HALAL[topic]
  if (!t) return null
  return (
    <div className="rounded-lg border border-emerald-500/30 bg-emerald-500/[0.07] px-3 py-2">
      <div className="flex items-start gap-2">
        <span className="mt-[1px] text-sm">☪️</span>
        <div className="min-w-0 flex-1">
          <p className="text-[12px] leading-snug text-emerald-200/90">{t.short}</p>
          <button
            onClick={() => setOpen((v) => !v)}
            className="mt-1 text-[11px] font-semibold text-emerald-400 hover:underline"
          >
            {open ? 'Свернуть' : 'Почему так?'}
          </button>
          {open && (
            <div className="mt-2 space-y-2 border-t border-emerald-500/20 pt-2">
              {t.full.split('\n\n').map((para, i) => (
                <p key={i} className="whitespace-pre-line text-[12px] leading-relaxed text-[var(--muted)]">
                  {para}
                </p>
              ))}
              {t.source && (
                <p className="text-[10px] italic text-[var(--muted)]">Источник: {t.source}</p>
              )}
            </div>
          )}
        </div>
      </div>
    </div>
  )
}
