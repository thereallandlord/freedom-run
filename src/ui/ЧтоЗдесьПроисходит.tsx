import { useEffect, useState } from 'react'
import type { Table } from '../engine/types'

/**
 * Объяснение правил в двух точках, где человек их и спрашивает.
 *
 * 🔴 ЗАЧЕМ. Живая игра 31 августа: новичок за столом трижды спрашивал вслух
 * «а что мне вообще надо сделать?», а при переходе на второй круг вопрос был
 * уже у всех — «вот эту логику я не понимаю». Правила объяснял хозяин стола
 * голосом по три раза за вечер. Камиль просил отдельно: уведомление в начале
 * партии — в чём суть и цель, и уведомление при переходе — в чём цель дальше.
 *
 * 🔴 ПОЧЕМУ ЭТО ЖИВЁТ В ИНТЕРФЕЙСЕ, А НЕ В СТОЛЕ. Партия пересобирается из
 * журнала ходов; всё, что попадает в стол, обязано быть воспроизводимым и
 * одинаковым у всех. «Я прочитал и закрыл» — личное дело каждого игрока и к
 * правде о партии отношения не имеет. Поэтому отметка о прочтении лежит в
 * браузере, привязана к комнате и к месту.
 */

const КЛЮЧ = 'freedom-run:прочитано:v1'

/*
 * Флаг снят: движок догнал текст. Выход из Круга больше не выкуп — активы
 * остаются, зарплата уходит, дела растут на 30%, а победа на втором круге
 * одна — купить свою мечту.
 */

function прочитано(): Record<string, true> {
  try {
    return JSON.parse(localStorage.getItem(КЛЮЧ) || '{}')
  } catch {
    // Приватное окно, забитая квота, отключённые куки — не повод падать.
    return {}
  }
}

function отметить(ключ: string) {
  try {
    localStorage.setItem(КЛЮЧ, JSON.stringify({ ...прочитано(), [ключ]: true }))
  } catch {
    /* см. выше: без отметки объяснение просто покажется ещё раз */
  }
}

function Окно({
  метка,
  заголовок,
  строки,
  кнопка,
  onClose,
}: {
  метка: string
  заголовок: string
  строки: { знак: string; текст: string }[]
  кнопка: string
  onClose: () => void
}) {
  return (
    <div
      className="modal-layer fixed inset-0 z-[69] grid place-items-center bg-black/80 p-4"
      onClick={onClose}
    >
      <div
        className="pop-in panel flex max-h-[90vh] w-full max-w-md flex-col rounded-2xl p-5"
        onClick={(e) => e.stopPropagation()}
      >
        <div className="caps text-[10px] font-bold text-accent">{метка}</div>
        <h2 className="mt-0.5 text-lg font-bold leading-tight">{заголовок}</h2>
        <div className="mt-3 space-y-2.5 overflow-y-auto">
          {строки.map((с, i) => (
            <div key={i} className="flex gap-2.5">
              <span className="mt-[1px] shrink-0 text-[15px] leading-none">{с.знак}</span>
              <p className="text-[13px] leading-snug text-[var(--muted)]">{с.текст}</p>
            </div>
          ))}
        </div>
        <button onClick={onClose} className="btn-primary mt-4 w-full">
          {кнопка}
        </button>
      </div>
    </div>
  )
}

export function ЧтоЗдесьПроисходит({
  table,
  meId,
  комната,
}: {
  table: Table
  meId?: string
  комната?: string
}) {
  const место = meId ? table.seats.find((s) => s.id === meId) : table.seats[table.turnIndex]
  const наПолосе = место?.track === 'fast'
  const основа = `${комната ?? 'дома'}:${место?.id ?? 'один'}`
  const ключСтарта = `${основа}:старт`
  const ключПолосы = `${основа}:полоса`

  const [показать, setПоказать] = useState<'старт' | 'полоса' | null>(null)

  useEffect(() => {
    const п = прочитано()
    /*
     * Полоса важнее старта: если человек добрался до второго круга, не
     * прочитав вступление, вступление ему уже не нужно.
     */
    if (наПолосе && !п[ключПолосы]) {
      setПоказать('полоса')
      return
    }
    if (!наПолосе && !п[ключСтарта]) setПоказать('старт')
  }, [наПолосе, ключСтарта, ключПолосы])

  if (!показать || !место) return null

  const закрыть = () => {
    отметить(показать === 'полоса' ? ключПолосы : ключСтарта)
    setПоказать(null)
  }

  if (показать === 'полоса') {
    return (
      <Окно
        метка="Второй круг"
        заголовок="Вы уволились. Что дальше"
        кнопка="Понятно, играем"
        onClose={закрыть}
        строки={[
          {
            знак: '🏠',
            текст:
              'Всё, что вы нажили, остаётся вашим: квартиры, дела, бумаги, партнёрский бизнес. Никто вас не выкупает — вы просто перестали ходить на работу.',
          },
          {
            знак: '💼',
            текст:
              'Зарплаты больше нет. Живёте на то, что приносят активы, — ради этого всё и затевалось.',
          },
          {
            знак: '📈',
            текст:
              'Ваши дела стали приносить больше: раньше вы забегали в них после работы, теперь занимаетесь ими целый день.',
          },
          {
            знак: '🎯',
            текст:
              'Рубеж свободы: доход с активов вдвое больше расходов. Это не победа, а точка, с которой деньги начинают копиться всерьёз.',
          },
          {
            знак: '✨',
            текст:
              'А побеждает тот, кто купил свою мечту: накопить наличными и дойти по доске до своей клетки. Мечта — то, что вы себе позволяете, когда свобода уже есть.',
          },
        ]}
      />
    )
  }

  return (
    <Окно
      метка="Как здесь играют"
      заголовок="Выбраться из бега по кругу"
      кнопка="Начинаем"
      onClose={закрыть}
      строки={[
        {
          знак: '🐹',
          текст:
            'Сейчас вы работаете за зарплату, и она вся уходит на расходы. Это и есть бег по кругу: доход растёт, расходы догоняют.',
        },
        {
          знак: '🏠',
          текст:
            'Выход один — активы: квартиры, дела, доли. Они приносят деньги, пока вы спите, и расходы за ними не тянутся.',
        },
        {
          знак: '🎯',
          текст:
            'Цель первого круга: доход с активов должен перекрыть расходы. Как перекрыл — можно увольняться, и зарплата больше не нужна.',
        },
        {
          знак: '🤝',
          текст:
            'Денег на сделку не хватает — зовите соседа в долю или просите в долг. Здесь торгуются, а не только кидают кубик.',
        },
        {
          знак: '☪️',
          текст:
            'Всё по-халяльному: процентных кредитов нет, наценка за рассрочку — за товар, а не за время. Где есть тонкость, на карточке будет пометка «почему так».',
        },
      ]}
    />
  )
}
