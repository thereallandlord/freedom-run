/**
 * Цена бумаги ходит сама, каждый ход.
 *
 * 🔴 ЗАЧЕМ. До 06.09 цена бумаги в игре НЕ МЕНЯЛАСЬ: она напечатана на
 * карточке, покупалась по случайной цене из вилки (перекошенной ВНИЗ, то есть
 * в пользу покупателя), а продавалась по печатной. Продажа была почти всегда
 * в плюс, причём в любой момент и без единого события — деньги из воздуха.
 * Камиль: «продавать в плюс странно», и позже — «цена меняется каждый ход, и
 * не так, что она скачет жёстко, а есть некая тенденция».
 *
 * 🔴 ЧТО ЭТО ЗА ДВИЖЕНИЕ. Не бросок кубика на каждый ход: у настоящей цены
 * есть память. Здесь три силы, и все три взяты из жизни:
 *   • СНОС — куда бумагу тянет вдолгую. У голубых фишек вверх, у мемкоина
 *     вниз, и это главная причина, почему на мемкоинах теряют.
 *   • ШУМ — случайное колебание. У сукука его почти нет, у мемкоина огромный.
 *   • ВОЗВРАТ К ЯКОРЮ — слабая тяга обратно к своей цене. Без него цена за
 *     сто семьдесят ходов уезжает в бесконечность или в ноль, и вилка на
 *     карточке становится враньём.
 *
 * 🔴 ПОЧЕМУ ХРАНИМ В СТОЛЕ, А НЕ СЧИТАЕМ НА ЛЕТУ. Партия пересобирается из
 * журнала ходов. Цена, посчитанная функцией от номера хода, пересчитывалась бы
 * на каждой отрисовке пятнадцать раз по сто семьдесят шагов; цена, лежащая в
 * столе и сдвигаемая ровно один раз за ход, — часть состояния, как и всё
 * остальное, и переигрывается сама собой.
 */

/** Нрав бумаги: насколько сильно её носит и куда тянет. */
export interface НравБумаги {
  /** Средний снос за ОДИН ход, в долях логарифма: 0.0025 ≈ +0,25%. */
  снос: number
  /** Разброс шума за один ход, в долях: 0.05 = ±5%. */
  шум: number
  /** Сила возврата к якорной цене, 0…1. Больше — крепче держит вилку. */
  возврат: number
  /**
   * Инерция: какая доля вчерашнего движения переносится на сегодня.
   *
   * 🔴 РАДИ НЕЁ ВСЁ И ЗАТЕВАЛОСЬ. Камиль просил «не так, что она скачет
   * жёстко, а есть некая тенденция». Чистая случайность рисует пилу, в
   * которой тенденции нет вовсе. Настоящая месячная связь соседних движений
   * у акции близка к нулю, поэтому больше 0,3 ставить нельзя — иначе бумага
   * становится предсказуемой и её научатся обыгрывать.
   */
  инерция: number
  /**
   * Ниже какой доли своей цены бумага упасть не может.
   *
   * 🔴 ПОЧЕМУ ЭТО ВАЖНО ИМЕННО ДЛЯ МЕМКОИНА. Пол работает как отражающая
   * стенка: упёршись в него, цена может только расти — и монета, которой
   * положено уйти в ноль, отскакивала и вырастала в четверти партий вместо
   * десятой. У мемкоина пол почти нулевой, потому что за ценой ничего не
   * стоит. У остальных бумаг за ценой компания или металл, и половина нижней
   * границы вилки — честная граница.
   */
  пол: number
}

/**
 * Нравы по классам. 🔴 ЦИФРЫ ЗАМЕРЕНЫ, А НЕ ПРИДУМАНЫ (06.09): по каждому
 * классу искали настоящую волатильность и доходность, потом пытались
 * опровергнуть. Ход игры принят за полторы недели — это 0,35 месяца и
 * примерно 35 ходов в году; отсюда пересчёт месячных и годовых цифр.
 *
 * Источники и разбор — в буглоге. Коротко, что выяснилось:
 *   • голубые фишки НЕ ловушка: 9% годовых, растут. Убыток частника здесь не
 *     в сделке, а в упущенном — он продаёт растущую бумагу, чтобы «зафик-
 *     сировать», и она едет дальше без него (растущую закрывают на 60% чаще
 *     падающей — эффект диспозиции, Odean).
 *   • отдельные волатильные акции: снос слегка ОТРИЦАТЕЛЬНЫЙ, качает вдвое.
 *   • золото: спокойный рост, но в минус закрывают 75% — покупают на пике.
 *   • крипта: +10% годовых при разбросе 20% в месяц — то есть почти шум.
 *   • мемкоин: −35% годовых и 85% доходят почти до нуля. Это и есть ловушка,
 *     и она честная, а не подкрученная.
 */
export type КлассБумаги = 'фишка' | 'акция' | 'сукук' | 'золото' | 'крипта' | 'мемкоин'

