/** К какому классу отнести бумагу. Мемкоин помечен на карточке. */
export function классБумаги(c: {
  symbol: string
  meme?: boolean
}): КлассБумаги {
  if (c.meme) return 'мемкоин'
  const s = c.symbol.toUpperCase()
  if (s === 'SUKUK') return 'сукук'
  if (s === 'GOLD') return 'золото'
  if (['BTC', 'ETH', 'SOL', 'TON'].includes(s)) return 'крипта'
  if (['AAPL', 'MSFT', 'GOOGL'].includes(s)) return 'фишка'
  return 'акция'
}

/**
 * Один шаг цены.
 *
 * `случайное` — число 0…1 от датчика стола: движение обязано быть
 * воспроизводимым при пересборке партии из журнала.
 */
export function шагЦены(
  цена: number,
  якорь: number,
  вилка: [number, number],
  нрав: НравБумаги,
  случайное: () => number,
  прошлоеДвижение = 0,
): { цена: number; движение: number } {
  const [низ, верх] = вилка
  /*
   * Шум складываем из трёх бросков: одна равномерная случайность даёт
   * «плоское» движение, при котором крупные скачки так же часты, как мелкие.
   * Сумма трёх похожа на настоящее распределение — мелких колебаний много,
   * крупные редки, но случаются.
   */
  const шок = (случайное() + случайное() + случайное() - 1.5) * (2 / 1.5) * нрав.шум
  const тяга = нрав.возврат * Math.log(якорь / Math.max(1, цена))
  // Инерция несёт часть вчерашнего движения — из неё и складывается тенденция.
  const движение = нрав.инерция * прошлоеДвижение + шок
  const следующая = цена * Math.exp(нрав.снос + тяга + движение)
  // Пол считается от ЯКОРЯ и нрава, а не от вилки: у мемкоина он почти ноль.
  const пол = Math.max(1, Math.round(Math.min(низ, якорь) * нрав.пол))
  const потолок = Math.round(верх * 2)
  /*
   * 🔴 ОКРУГЛЯЕМ ПО РАЗМЕРУ ЦЕНЫ, А НЕ ВСЕГДА ДО СОТЕН. Жёсткое округление до
   * ста рублей — это шаг в треть цены для монеты за триста, и оно САМО
   * держало мемкоин на плаву: упасть ниже сотни он просто не мог. Замер это
   * и показал — монета выживала в 30% партий вместо десяти.
   */
  const шаг = следующая >= 5000 ? 100 : следующая >= 500 ? 10 : 1
  const округлённая = Math.round(следующая / шаг) * шаг
  const итог = Math.max(пол, Math.min(потолок, округлённая || пол))
  return { цена: итог, движение }
}
