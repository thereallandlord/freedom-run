  акция: { снос: -0.0006, шум: 0.089, возврат: 0.03, инерция: 0.25, пол: 0.4 },
  // 1,5%/мес, +4,5% годовых: арендный сертификат, доход в самой бумаге.
  сукук: { снос: 0.0013, шум: 0.009, возврат: 0.08, инерция: 0.15, пол: 0.8 },
