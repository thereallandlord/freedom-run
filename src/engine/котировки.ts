/**
 * Цена бумаги ходит сама, каждый ход.
 *
 * 🔴 ЗАЧЕМ. До 06.09 цена бумаги в игре НЕ МЕНЯЛАСЬ: она напечатана на
 * карточке, покупалась по случайной цене из вилки (перекошенной ВНИЗ, то есть
 * в пользу покупателя), а продавалась по печатной. Продажа была почти всегда
 * в плюс, причём в любой момент и без единого события — деньги из воздуха.
 * Камиль: «продавать в плюс странно», и позже — «цена меняется каждый ход, и
 * не так, что она скачет жёстко, а есть некая тенденция».
 *
 * 🔴 ЧТО ЭТО ЗА ДВИЖЕНИЕ. Не бросок кубика на каждый ход: у настоящей цены
 * есть память. Здесь три силы, и все три взяты из жизни:
 *   • СНОС — куда бумагу тянет вдолгую. У голубых фишек вверх, у мемкоина
 *     вниз, и это главная причина, почему на мемкоинах теряют.
 *   • ШУМ — случайное колебание. У сукука его почти нет, у мемкоина огромный.
 *   • ВОЗВРАТ К ЯКОРЮ — слабая тяга обратно к своей цене. Без него цена за
 *     сто семьдесят ходов уезжает в бесконечность или в ноль, и вилка на
 *     карточке становится враньём.
 *
 * 🔴 ПОЧЕМУ ХРАНИМ В СТОЛЕ, А НЕ СЧИТАЕМ НА ЛЕТУ. Партия пересобирается из
 * журнала ходов. Цена, посчитанная функцией от номера хода, пересчитывалась бы
 * на каждой отрисовке пятнадцать раз по сто семьдесят шагов; цена, лежащая в
 * столе и сдвигаемая ровно один раз за ход, — часть состояния, как и всё
 * остальное, и переигрывается сама собой.
 */

/** Нрав бумаги: насколько сильно её носит и куда тянет. */
export interface НравБумаги {
  /** Средний снос за ОДИН ход, в долях: 0.002 = +0,2%. */
  снос: number
  /** Разброс шума за один ход, в долях: 0.05 = ±5%. */
  шум: number
  /** Сила возврата к якорной цене, 0…1. Больше — крепче держит вилку. */
  возврат: number
}

/**
 * Нравы по классам. Цифры выставляются по замеру реальных бумаг —
 * см. соседний файл с параметрами и комментарий у каждого класса.
 */
export type КлассБумаги = 'фишка' | 'акция' | 'сукук' | 'золото' | 'крипта' | 'мемкоин'

export const НРАВЫ: Record<КлассБумаги, НравБумаги> = {
  // Крупные технологические: растут вдолгую, качает умеренно.
  фишка: { снос: 0.0025, шум: 0.035, возврат: 0.02 },
  // Отдельные волатильные акции: тот же снос, качает вдвое сильнее.
  акция: { снос: 0.002, шум: 0.07, возврат: 0.03 },
  // Сукук — арендный сертификат: почти не качает, доход в самой бумаге.
  сукук: { снос: 0.0015, шум: 0.006, возврат: 0.08 },
  // Золото: медленный рост, спокойное колебание.
  золото: { снос: 0.002, шум: 0.025, возврат: 0.03 },
  // Крупная крипта: сильный разброс, снос слабо положительный.
  крипта: { снос: 0.001, шум: 0.12, возврат: 0.02 },
  // Мемкоин: снос ОТРИЦАТЕЛЬНЫЙ и разброс огромный — на них и теряют.
  мемкоин: { снос: -0.02, шум: 0.22, возврат: 0.01 },
}

/** К какому классу отнести бумагу. Мемкоин помечен на карточке. */
export function классБумаги(c: {
  symbol: string
  meme?: boolean
}): КлассБумаги {
  if (c.meme) return 'мемкоин'
  const s = c.symbol.toUpperCase()
  if (s === 'SUKUK') return 'сукук'
  if (s === 'GOLD') return 'золото'
  if (['BTC', 'ETH', 'SOL', 'TON'].includes(s)) return 'крипта'
  if (['AAPL', 'MSFT', 'GOOGL'].includes(s)) return 'фишка'
  return 'акция'
}

/**
 * Один шаг цены.
 *
 * `случайное` — число 0…1 от датчика стола: движение обязано быть
 * воспроизводимым при пересборке партии из журнала.
 */
export function шагЦены(
  цена: number,
  якорь: number,
  вилка: [number, number],
  нрав: НравБумаги,
  случайное: () => number,
): number {
  const [низ, верх] = вилка
  /*
   * Шум складываем из трёх бросков: одна равномерная случайность даёт
   * «плоское» движение, при котором крупные скачки так же часты, как мелкие.
   * Сумма трёх похожа на настоящее распределение — мелких колебаний много,
   * крупные редки, но случаются.
   */
  const шок = (случайное() + случайное() + случайное() - 1.5) * (2 / 1.5) * нрав.шум
  const тяга = нрав.возврат * Math.log(якорь / Math.max(1, цена))
  const следующая = цена * Math.exp(нрав.снос + тяга + шок)
  /*
   * 🔴 Вилку раздвигаем вдвое от печатной: карточка обещает «где обычно
   * ходит», а не «дальше не бывает». Жёсткий зажим по печатной вилке делал
   * из цены пружину — она липла к краям и переставала быть похожей на рынок.
   */
  const пол = Math.max(1, Math.round(низ / 2))
  const потолок = Math.round(верх * 2)
  return Math.max(пол, Math.min(потолок, Math.round(следующая / 100) * 100 || пол))
}
