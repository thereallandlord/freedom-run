/**
 * Своё дело растёт: ещё одна точка и франшиза собственного дела.
 *
 * 🔴 ЗАЧЕМ. Решение Камиля 11.09 (вариант Б). Замер до настоящего конца партии:
 * с GreenLeaf из Круга выходят 98%, без него — 5%, а если брать всё подряд, что
 * по карману, — 3%, и 174 из 240 разоряются. Настоящие дела за партию до
 * свободы не дорастали: растёт только структура. А принцип Камиля из реестра
 * 16–19.08 — «не агитировать: выйти можно на любой нише». В жизни владелец дела
 * выходит ровно так: открывает вторую точку, потом продаёт франшизу.
 *
 * Цифры GreenLeaf не трогаем (решение 20.08). Ручки ниже подбираются замером:
 * без GreenLeaf должна выходить хотя бы половина, а GreenLeaf — оставаться
 * самой быстрой дорогой.
 */
import type { BusinessAsset, Ledger } from './types'

/**
 * Вторая точка — половина цены готового дела. 🔴 При 90% она окупалась почти
 * в полтора раза дольше, чем покупка чужого дела с карточки: платишь почти
 * столько же, а управляющий забирает свою долю, — кнопка была ловушкой.
 * Половина — это стены и оборудование: в цене готового дела сидят ещё
 * клиентская база и имя, а их новой точке покупать не нужно. Открыть свой
 * барбершоп в Казани стоит около миллиона при цене готового 1,9 млн.
 * Замер 11.09 (Камиль: «да, ускорь» старт без GreenLeaf): 60% → 50% сдвинули
 * выход без GreenLeaf с 247-го на 245-й ход и сократили игру в одиночку.
 */
export const ТОЧКА_ОТ_ЦЕНЫ = 0.5
/** Сколько точек можно открыть сверх первой: сеть до шести. */
export const ТОЧЕК_СВЕРХ_ПЕРВОЙ = 5
/** Франшизу продают, когда своих точек не меньше этого (первая + ещё две). */
export const ФРАНШИЗА_ОТ_ТОЧЕК = 3
/** Упаковка франшизы — юристы, брендбук, обучение — от цены точки. */
export const ФРАНШИЗА_ОТ_ЦЕНЫ = 0.5
/** Роялти на старте, прибавка каждую зарплату и потолок — в долях дохода одной точки. */
export const ФРАНШИЗА_СТАРТ = 0.2
export const ФРАНШИЗА_РОСТ = 0.15
export const ФРАНШИЗА_ПОТОЛОК = 4

/** Цена точки на рынке — без наценки за рассрочку, если дело брали в рассрочку. */
function ценаДела(b: BusinessAsset): number {
  return b.value ?? b.cost
}

/**
 * Полный доход одной точки. У купленного в рассрочку в `cashFlow` уже вычтен
 * платёж — а новая точка берётся наличными, и платежа у неё нет.
 */
export function доходТочки(b: BusinessAsset): number {
  return b.cashFlow + (b.installmentMonthly ?? 0)
}

/** С какого дела можно растить сеть: своё, обычное, первая точка, не франшиза. */
function корень(b: BusinessAsset): boolean {
  return !b.gl && !(b.partnerId && !b.investorShare) && !b.точкаОт && !b.франшизаОт
}

export function точекУДела(l: Ledger, b: BusinessAsset): number {
  return 1 + l.businesses.filter((x) => x.точкаОт === b.id).length
}

export function ценаТочки(b: BusinessAsset): number {
  return Math.round((ценаДела(b) * ТОЧКА_ОТ_ЦЕНЫ) / 1000) * 1000
}

export function ценаФраншизы(b: BusinessAsset): number {
  return Math.round((ценаДела(b) * ФРАНШИЗА_ОТ_ЦЕНЫ) / 1000) * 1000
}

/**
 * Почему нельзя открыть точку — или `null`, если можно.
 * 🔴 Вторая точка — только когда первая работает БЕЗ тебя, то есть с
 * управляющим: в двух местах сразу не постоишь.
 */
export function почемуНельзяТочку(l: Ledger, b: BusinessAsset): string | null {
  if (!корень(b)) return 'точку открывают от своего основного дела'
  if (!b.managerPct) return 'сначала наймите управляющего в первую точку — в двух местах сразу не постоишь'
  if (точекУДела(l, b) > ТОЧЕК_СВЕРХ_ПЕРВОЙ) return 'сеть уже полная'
  if (l.cash < ценаТочки(b)) return `не хватает денег: нужно ${ценаТочки(b).toLocaleString('ru')} ₽`
  return null
}

export function почемуНельзяФраншизу(l: Ledger, b: BusinessAsset): string | null {
  if (!корень(b)) return 'франшизу продают от своего основного дела'
  if (l.businesses.some((x) => x.франшизаОт === b.id)) return 'франшиза уже продаётся'
  if (точекУДела(l, b) < ФРАНШИЗА_ОТ_ТОЧЕК) return `нужно не меньше ${ФРАНШИЗА_ОТ_ТОЧЕК} своих точек — формат должен быть проверен`
  if (l.cash < ценаФраншизы(b)) return `не хватает денег: нужно ${ценаФраншизы(b).toLocaleString('ru')} ₽`
  return null
}
