/**
 * Бинар: слабая нога решает, пара закрывает уровень, перелив закрывает ногу.
 * Запуск: npx tsx src/engine/binartest.ts
 */
import {
  glInitialState, glПришлиЛюди, glПереливНаставника, глубинаПо,
  реферальныйЗа, заУровень, ширинаЗа, НАБОР_PV, GL_PACKAGES,
} from './greenleaf'

let провалов = 0
const п = (что: string, ок: boolean, факт = '') => {
  console.log(`  ${ок ? '✅' : '❌'} ${что}${факт ? ' — ' + факт : ''}`)
  if (!ок) провалов++
}

console.log('█ ЦИФРЫ ИЗ МАРКЕТИНГ-ПЛАНА')
п('реферальный за базовый набор = 914 ₽', реферальныйЗа(НАБОР_PV) === 914, `${реферальныйЗа(НАБОР_PV)} ₽`)
п('за уровень глубины = 5 852 ₽', заУровень() === 5852, `${заУровень()} ₽`)
const ширинаПлатина = ширинаЗа(НАБОР_PV, GL_PACKAGES[0].gbRate)
const ширинаКорона = ширинаЗа(НАБОР_PV, GL_PACKAGES[2].gbRate)
п('ширина Платины за 275 PV = 1 828 ₽ (как в плане)', ширинаПлатина === 1828, `${ширинаПлатина} ₽`)
п('ширина Короны за 275 PV = 2 743 ₽', ширинаКорона === 2743, `${ширинаКорона} ₽`)
п('пара на Платине = 9 508 ₽',
  реферальныйЗа(НАБОР_PV) * 2 + ширинаПлатина + заУровень() === 9508,
  `${реферальныйЗа(НАБОР_PV) * 2 + ширинаПлатина + заУровень()} ₽`)

console.log('\n█ СЛАБАЯ НОГА РЕШАЕТ')
let g = glInitialState('platinum', 1)
let r = glПришлиЛюди(g, НАБОР_PV * 3, 0, 3)
g = r.next
п('трое в одну ногу — уровень НЕ закрылся', глубинаПо(g.left, g.right) === 0, `слабая ${Math.min(g.left, g.right)} PV`)
п('но реферальные пришли', r.деньги === 914 * 3, `${r.деньги} ₽`)
п('игра объяснила, почему денег за ногу нет', r.заметки.some((z) => /слабая/i.test(z)))

console.log('\n█ ПАРА ЗАКРЫВАЕТ УРОВЕНЬ')
r = glПришлиЛюди(g, 0, НАБОР_PV, 1)
g = r.next
п('уровень закрылся', глубинаПо(g.left, g.right) === 1)
п('пришли реферальный и глубина', r.деньги === 914 + 5852, `${r.деньги} ₽`)
п('сказано про пару', r.заметки.some((z) => /Пара сложилась/.test(z)))

console.log('\n█ ПЕРЕЛИВ НАСТАВНИКА ЗАКРЫВАЕТ ОТСТАЮЩУЮ НОГУ')
let g2 = glInitialState('platinum', 1)
g2 = glПришлиЛюди(g2, НАБОР_PV * 3, 0, 3).next
const r2 = glПереливНаставника(g2, НАБОР_PV * 3)
п('перелив ушёл в ПРАВУЮ — она отставала', r2.next.right === НАБОР_PV * 3, `слева ${r2.next.left}, справа ${r2.next.right}`)
п('закрылось три уровня разом', глубинаПо(r2.next.left, r2.next.right) === 3)
п('денег за глубину — три уровня', r2.деньги === 5852 * 3, `${r2.деньги} ₽`)
п('реферального за перелив НЕТ — их привёл не ты', !r2.заметки.some((z) => /наставника: /.test(z)))

console.log(провалов ? `\n❌ ПРОВАЛОВ: ${провалов}` : '\n✅ БИНАР СЧИТАЕТ ВЕРНО')
if (провалов) throw new Error('бинар считает неверно')
