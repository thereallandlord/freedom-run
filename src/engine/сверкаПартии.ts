/**
 * Сошлась ли партия из кабинета после повтора журнала.
 *
 * 🔴 ЗАЧЕМ. Кабинет хранит журнал ходов без отпечатка правил, а «Поднять
 * партию с того же места» просто прогоняет его заново. После любой правки
 * данных — колод, профессий — недоигранная партия молча становилась другой:
 * другие карты, другие деньги, другой победитель. У местных сохранений от
 * этого есть отпечаток, у кабинетных не было ничего.
 *
 * Сервер трогать не нужно: вместе с журналом кабинет хранит итог моего места
 * на момент записи — номер хода и капитал. Если повтор к ним не пришёл, данные
 * с тех пор менялись, и честнее сказать об этом, чем подсунуть человеку
 * чужую партию под видом его собственной.
 */
import { replayTable, type TableSetup } from './table'
import { netWorth } from './ledger'
import type { TableEvent } from './events'

export interface ОжиданиеКабинета {
  turns: number
  seatId: string
  netWorth: number
}

export function сверитьСКабинетом(
  setup: TableSetup,
  journal: TableEvent[],
  ожидание: ОжиданиеКабинета,
): { сошлась: boolean; причина?: string } {
  let t
  try {
    t = replayTable(setup, journal)
  } catch {
    return { сошлась: false, причина: 'журнал не пересобирается' }
  }
  if (t.turnCounter !== ожидание.turns)
    return { сошлась: false, причина: `ход ${t.turnCounter} вместо ${ожидание.turns}` }
  const моё = t.seats.find((s) => s.id === ожидание.seatId)
  if (!моё) return { сошлась: false, причина: 'моего места за столом нет' }
  const капитал = Math.round(netWorth(моё.ledger))
  if (Math.abs(капитал - ожидание.netWorth) > 1)
    return { сошлась: false, причина: `капитал ${капитал} вместо ${ожидание.netWorth}` }
  return { сошлась: true }
}
