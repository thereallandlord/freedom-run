const беды: string[] = []

/* 1. Лестница рубежей: густо на старте, редко на больших числах. */
const ожидание: [number, number][] = [
  [0, 0],
  [4_999, 0],
  [5_000, 5_000],
  [9_900, 5_000],
  [10_000, 10_000],
  [24_640, 10_000],
  [30_000, 25_000],
  [50_000, 50_000],
  [99_000, 50_000],
  [100_000, 100_000],
  [250_000, 200_000],
]
for (const [доход, ждём] of ожидание) {
  const факт = рубежПартнёрского(доход)
  if (факт !== ждём) беды.push(`рубеж при ${доход}: ждали ${ждём}, вышло ${факт}`)
}
console.log(`рубежей проверено: ${ожидание.length}`)

/*
 * 🔴 Отдельно ловим ту самую дыру, из-за которой всё и молчало: между 5 000 и
 * 100 000 должно быть НЕ МЕНЬШЕ трёх ступеней. С одним шагом в сотню их ноль.
 */
const ступени = new Set(
  [5_000, 10_000, 24_640, 30_000, 50_000, 99_000].map((v) => рубежПартнёрского(v)),
)
ступени.delete(0)
if (ступени.size < 3) беды.push(`ступеней до сотни тысяч: ${ступени.size} — снова тишина на весь год`)
console.log(`ступеней до 100 000: ${ступени.size}`)

