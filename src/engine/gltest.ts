  t = applyTableEvent(t, ход)
  if (t === до) break
  for (const плашка of t.лента ?? []) {
    if (плашка.id > виделоСь) {
      виделоСь = плашка.id
      собрано.push({ text: плашка.text, кому: плашка.кому })
    }
  }
