/**
 * Второй паспорт действительно что-то даёт.
 *
 * 🔴 До этой правки он не делал НИЧЕГО: во всём движке `citizenship` читался
 * ровно в одном месте — в мировом событии «трение», — а обе такие карточки
 * убраны по решению Камиля. Паспорт стоил денег и был чистой ловушкой.
 * Проверка нужна именно поэтому: пользу легко потерять снова, и заметить это
 * будет нечем.
 */
import { CITIZENSHIP, ЗАРУБЕЖНЫЕ_КАТЕГОРИИ, надбавкаИностранца } from './ledger'
import type { Ledger } from './types'

const без = { citizenship: undefined } as unknown as Ledger
const с = { citizenship: 'Гражданство Турции' } as unknown as Ledger

let плохо = 0
const итог = (ок: boolean, т: string) => {
  console.log(`${ок ? '✅' : '❌'} ${т}`)
  if (!ок) плохо += 1
}

итог(
  ЗАРУБЕЖНЫЕ_КАТЕГОРИИ.every((k) => надбавкаИностранца(с, k) > 0),
  `с паспортом возврат есть по всем зарубежным категориям (${ЗАРУБЕЖНЫЕ_КАТЕГОРИИ.join(', ')})`,
)
итог(
  ЗАРУБЕЖНЫЕ_КАТЕГОРИИ.every((k) => надбавкаИностранца(без, k) === 0),
  'без паспорта возврата нет',
)
итог(надбавкаИностранца(с, 'aptKZN') === 0, 'на российское жильё возврат не распространяется')
итог(надбавкаИностранца(с, 'bizFood') === 0, 'на бизнес возврат не распространяется')
итог(надбавкаИностранца(с, undefined) === 0, 'без категории ничего не ломается')

// И самое главное: за паспорт просят деньги — значит выгода обязана быть названа.
итог(
  CITIZENSHIP.every((c) => /паспорт|резидент|местн/i.test(c.note) && /10%|надбавк/i.test(c.note)),
  'в описании каждого паспорта сказано, что он даёт',
)

console.log(плохо === 0 ? '\n✅ ПАСПОРТ ДАЁТ ТО, ЗА ЧТО ПЛАТЯТ' : `\n❌ ПРОБЛЕМ: ${плохо}`)
if (плохо) (globalThis as { process?: { exitCode?: number } }).process!.exitCode = 1
