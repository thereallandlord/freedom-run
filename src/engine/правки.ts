/**
 * Правки хозяина игры: числа и тексты, заданные из панели поверх колод.
 *
 * 🔴 ЗАЧЕМ ОТДЕЛЬНЫМ СЛОЕМ, А НЕ ПРАВКОЙ ФАЙЛОВ. Колоды лежат в репозитории и
 * меняются только выкатом. Панель должна давать поменять цифру, не трогая код,
 * — значит нужен слой поверх, который накладывается на загруженные данные.
 *
 * 🔴 ЭТО МЕНЯЕТ ПАРТИЮ. Стол пересобирается из журнала ходов, и карты берутся
 * по индексу в перетасованной колоде. Значит правка делает СТАРЫЕ журналы
 * недействительными: те же ходы дадут другие карты. Поэтому правки участвуют
 * в отпечатке сохранения (см. useGame): не сошлось — партию честно не
 * восстанавливаем, вместо того чтобы подсунуть человеку подделку.
 *
 * 🔴 ПРАВКИ ПРИМЕНЯЮТСЯ ДО ПЕРВОГО СТОЛА. Если положить их посреди партии,
 * половина ходов будет посчитана по старым числам, половина по новым, и
 * пересборка из журнала развалится. Загрузка идёт один раз при старте
 * страницы (main.tsx), до того как появится любой стол.
 */

/** Что можно переопределить у карточки: числа и тексты, но не её вид и не id. */
export type ПравкаКарточки = Record<string, string | number | boolean>

export interface Правки {
  /** По id карточки: `{ 'sd-park-ufa': { cashFlow: 6000 } }`. */
  карточки?: Record<string, ПравкаКарточки>
  /** Общие рычаги игры: срок рассрочки, множитель выкупа и прочее. */
  правила?: Record<string, number>
  /** Когда сохранены — для подписи в панели. */
  когда?: string
}

let текущие: Правки = {}
/**
 * Счётчик установок. По нему сбрасываются кэши колод: без него правка легла бы
 * в память, а игра продолжала бы отдавать старые карточки из кэша.
 */
let версия = 0

export function установитьПравки(п: Правки | null | undefined): void {
  текущие = п && typeof п === 'object' ? п : {}
  версия += 1
}

export function правкиВерсия(): number {
  return версия
}

export function правкиКарточек(): Record<string, ПравкаКарточки> {
  return текущие.карточки ?? {}
}

export function правкиПравил(): Record<string, number> {
  return текущие.правила ?? {}
}

export function всеПравки(): Правки {
  return текущие
}

export function естьПравки(): boolean {
  return (
    Object.keys(текущие.карточки ?? {}).length > 0 ||
    Object.keys(текущие.правила ?? {}).length > 0
  )
}

/**
 * Наложить правки на список карточек.
 *
 * 🔴 Только поля, которые в карточке УЖЕ ЕСТЬ. Иначе опечатка в панели
 * («cashflow» вместо «cashFlow») тихо добавила бы карточке лишнее поле, а
 * настоящее осталось бы прежним: правка «не сработала» без единого сообщения.
 */
export function наложить<T extends { id: string }>(карточки: T[]): T[] {
  const п = правкиКарточек()
  if (!Object.keys(п).length) return карточки
  return карточки.map((c) => {
    const своя = п[c.id]
    if (!своя) return c
    const из: Record<string, unknown> = {}
    for (const [k, v] of Object.entries(своя)) {
      if (k in (c as object)) из[k] = v
    }
    return Object.keys(из).length ? ({ ...c, ...из } as T) : c
  })
}
