// ─────────────── БИНАР: две ноги, глубина, слабая нога ───────────────
/*
 * 🔴 Модель НЕ полная и это осознанно. Настоящий бинар считает пятьдесят
 * поколений, переливы и компрессию — в партию это не поместится, и человеку
 * не нужно. Считаем ровно три вещи, ради которых Камиль и хочет GreenLeaf
 * в игре:
 *   1) решает СЛАБАЯ нога, а не общая масса людей;
 *   2) пара (человек слева И справа) закрывает уровень и приносит деньги;
 *   3) перелив наставника закрывает одну ногу за тебя.
 *
 * 🔴 И главное про деньги: месячный доход структуры (`baseFlow`) остаётся
 * прежним — Камиль просил экономику не пересобирать. Ноги добавляют только
 * РАЗОВЫЕ выплаты, которые в жизни и приходят разово: за лично приглашённого
 * и за новую глубину. Ежемесячный бонус ширины — это и есть baseFlow, второй
 * раз его не платим.
 *
 * Цифры проверены по внутреннему маркетинг-плану и сверены с журналами
 * начислений живых кабинетов (см. vault/greenleaf-цифры-маркетинг-плана-ФАКТЫ).
 */

/** Рублей за единицу PV в выплате: курс плана 70 минус удержание 5%. */
export const PV_РУБЛЬ = 70 * 0.95

/** Базовый набор партнёра. От него считаются все выплаты. */
export const НАБОР_PV = 275

/** Реферальный бонус: 5% от набора приглашённого. */
export const РЕФЕРАЛЬНЫЙ_PCT = 5

/** Глубина: фиксированные 88 PV за каждый новый закрытый уровень. */
export const ГЛУБИНА_PV = 88

/** Сколько PV в слабой ноге закрывают один уровень глубины. */
export const УРОВЕНЬ_PV = НАБОР_PV

/*
 * 🔴 Округляем ВНИЗ, как сам маркетинг-план: там написано
 * «10%*275*70*0,95=1828 руб.», хотя точное значение 1828,75. При обычном
 * округлении сумма за пару вышла бы 9 509 вместо 9 508 из документа —
 * мелочь, но игра не должна расходиться с бумагой, по которой люди считают.
 */
export const реферальныйЗа = (pv: number) =>
  Math.floor((pv * РЕФЕРАЛЬНЫЙ_PCT * PV_РУБЛЬ) / 100)

export const заУровень = () => Math.floor(ГЛУБИНА_PV * PV_РУБЛЬ)

/** Бонус ширины: процент пакета от объёма слабой ноги. */
export const ширинаЗа = (pv: number, gbRate: number) =>
  Math.floor((pv * gbRate * PV_РУБЛЬ) / 100)

/** Сколько уровней глубины закрыто: считает СЛАБАЯ нога. */
export const глубинаПо = (left: number, right: number) =>
  Math.floor(Math.min(left, right) / УРОВЕНЬ_PV)

