/**
 * Ноги подрастают вместе со структурой — не только от карточек.
 *
 * 🔴 Решение Камиля 20.08: в норме растут ОБЕ ноги примерно одинаково — так
 * и выглядит бизнес, когда идёт трафик и работают лидеры. Перекос создают
 * карточки: то одна сторона просела, то выровнялась, то другая отстала. Если
 * бы ноги двигались только карточками, они бы почти всё время стояли, и
 * человек не увидел бы главного — что растут именно две стороны.
 *
 * PV считаем ОТ ДЕНЕГ, а не наоборот: месячный доход структуры — это и есть
 * бонус ширины со слабой ноги, значит слабая нога обязана ему соответствовать.
 * Так картинка на экране не разойдётся с кошельком.
 */
export function glНогиЗаМесяц(g: GlState, доходСтруктуры: number): GlState {
  const ставка = glPackage(g.packageId).gbRate
  if (!ставка) return g
  // Сколько PV в слабой ноге объясняют этот доход.
  const нужноСлабой = Math.round((доходСтруктуры * 100) / (ставка * PV_РУБЛЬ))
  const слабаяСейчас = Math.min(g.left, g.right)
  const прирост = Math.max(0, нужноСлабой - слабаяСейчас)
  if (прирост <= 0) return g
  /*
   * Слабой ноге отдаём ровно прирост, сильной — чуть больше: в жизни перевес
   * никогда не исчезает полностью, но и не растёт бесконечно.
   */
  const влево = g.left <= g.right
  const next: GlState = {
    ...g,
    left: g.left + (влево ? прирост : Math.round(прирост * 1.15)),
    right: g.right + (влево ? Math.round(прирост * 1.15) : прирост),
  }
  /*
   * 🔴 Уровни, закрытые ЭТИМ ростом, помечаем оплаченными и денег за них не
   * даём: они уже сидят в месячном доходе структуры. Иначе они копились бы
   * молча, и первая же карточка выплатила бы их пачкой — на десятой зарплате
   * это семьдесят тысяч из ниоткуда.
   *
   * Платят только уровни, закрытые ПРИХОДОМ ЛЮДЕЙ по карточке: там это и есть
   * то самое событие, которое игра должна объявить.
   */
  next.depthPaid = Math.max(g.depthPaid, глубинаПо(next.left, next.right))
  return next
}

/** Что случилось в бинаре: разовые деньги и человеческое объяснение. */
export interface ПриходБинара {
  next: GlState
  деньги: number
  заметки: string[]
}

/**
 * Пришли люди в ноги. Возвращает разовые выплаты и объяснения к ним.
 *
 * @param слева   сколько PV пришло в левую ногу
 * @param справа  сколько PV пришло в правую
 * @param лично   сколько из них вы привели САМИ (по ним идёт реферальный)
 */
export function glПришлиЛюди(
  g: GlState,
  слева: number,
  справа: number,
  лично: number,
): ПриходБинара {
  const next: GlState = { ...g, left: g.left + слева, right: g.right + справа }
  const заметки: string[] = []
  let деньги = 0

  if (лично > 0) {
    const сумма = реферальныйЗа(НАБОР_PV) * лично
    деньги += сумма
    next.personals = g.personals + лично
    заметки.push(
      `Бонус наставника: ${fmt(сумма)} за ${лично === 1 ? 'лично приглашённого' : `${лично} лично приглашённых`}. ` +
        `Это 5% от их набора — платят сразу, за сам факт входа.`,
    )
  }

  const былаГлубина = g.depthPaid
  const сталаГлубина = глубинаПо(next.left, next.right)
  if (сталаГлубина > былаГлубина) {
    const уровней = сталаГлубина - былаГлубина
    const сумма = заУровень() * уровней
    деньги += сумма
    next.depthPaid = сталаГлубина
    заметки.push(
      уровней === 1
        ? `Пара сложилась: закрыт ${сталаГлубина}-й уровень глубины — ${fmt(сумма)}. ` +
          `Уровень платят только когда человек есть И слева, И справа.`
        : `Закрыто уровней глубины: ${уровней} — ${fmt(сумма)}.`,
    )
  }

  /*
   * Слабая нога — сердце бизнеса. Её показываем ВСЕГДА, даже когда денег за
   * этот приход не пришло: именно так человек и понимает, почему нельзя
   * растить одну сторону.
   */
  const слабаяДо = Math.min(g.left, g.right)
  const слабаяПосле = Math.min(next.left, next.right)
  if (слабаяПосле > слабаяДо) {
    заметки.push(
      `Слабая нога подросла: ${слабаяПосле} PV. По ней и считается ваш ежемесячный доход.`,
    )
  } else if (слева + справа > 0) {
    const сильная = next.left > next.right ? 'левая' : 'правая'
    заметки.push(
      `Люди пришли, но ${сильная} нога и так была больше — на доход это пока не повлияло. ` +
        `Платит слабая: ${слабаяПосле} PV.`,
    )
  }

  return { next, деньги, заметки }
}

/** Перелив наставника: он закрывает ОТСТАЮЩУЮ ногу, как и в жизни. */
export function glПереливНаставника(g: GlState, pv: number): ПриходБинара {
  const вЛевую = g.left <= g.right
  return glПришлиЛюди(g, вЛевую ? pv : 0, вЛевую ? 0 : pv, 0)
}

/** Сколько ещё пар нужно, чтобы окупить вход. Для подсказки на карточке. */
export function glПарДоОкупаемости(g: GlState): number {
  const ценаВхода = glPackage(g.packageId).price
  const заПару =
    реферальныйЗа(НАБОР_PV) * 2 + заУровень() + ширинаЗа(НАБОР_PV, glPackage(g.packageId).gbRate)
  return Math.max(0, Math.ceil(ценаВхода / Math.max(1, заПару)) - glглубина(g))
}

export const glглубина = (g: GlState) => g.depthPaid

/** Можно ли сейчас взять этот промоушен и почему нет. */
export function glPromoReady(g: GlState, p: GlPromo): { ready: boolean; why: string } {
  if (g.age < p.warmupPaydays)
    return { ready: false, why: `Бизнес слишком молодой — нужно ещё ${p.warmupPaydays - g.age} зарплат` }
  const last = g.lastPromo[p.id]
  if (last !== undefined && g.age - last < p.everyPaydays)
    return { ready: false, why: `Брали недавно — можно через ${p.everyPaydays - (g.age - last)} зарплат` }
  const grown = g.volume - (g.lastPromoVolume[p.id] ?? 0)
  if (grown < p.needVolume)
    return {
      ready: false,
      why: `План не закрыт: структура дала ${fmt(grown)} из нужных ${fmt(p.needVolume)} за период`,
    }
  return { ready: true, why: '' }
}

/** Доход структуры со всеми множителями, без пенсии за ранг. */
export function glStructureIncome(g: GlState): number {
  const withPackage = g.baseFlow * glPackage(g.packageId).mul
  const withTriangle = g.triangle ? withPackage * GL_TRIANGLE_BONUS : withPackage
  const withDip = g.dipLeft > 0 ? withTriangle * g.dipMul : withTriangle
  return Math.round(withDip / 100) * 100
}

/**
 * Какая доля дохода партнёрского бизнеса работает БЕЗ тебя.
 *
 * 🔴 Поправка Камиля 18.08: «в GreenLeaf ты тоже сначала работаешь сам, как в
 * любом бизнесе». Управляющего здесь не нанимают — его роль играет САМА
 * структура: чем она больше и чем больше в ней выросло лидеров, тем меньше
 * зависит от тебя лично. Поэтому доля растёт вместе с рангом, а не даётся
 * сразу.
 */
export function glFreedomShareByLevel(level: number): number {
  switch (level) {
    case 0:
      return 0 // сам бегаешь, сам приводишь — это работа
    case 1:
      return 40 // появились первые самостоятельные люди
    case 2:
      return 70 // под ними уже свои команды
    default:
      return 100 // структура живёт без тебя
  }
}

export function glFreedomShare(g: GlState): number {
  return glFreedomShareByLevel(glRankFor(g.volume).level)
}

/** Всё, что партнёрский бизнес приносит в месяц: структура плюс пенсия за ранг. */

/** Стадия партнёрского бизнеса: 1 — сам двигатель, 2 — структура шевелится, 3 — ранг. */
export type GlСтадия = 1 | 2 | 3
export function glСтадия(g: GlState): GlСтадия {
  const level = glRankFor(g.volume).level
  return level === 0 ? 1 : level === 1 ? 2 : 3
}

export function glTotalIncome(g: GlState): number {
  return glStructureIncome(g) + glRankFor(g.volume).pension
}

/** Доплата до старшего пакета. Апгрейд доступен всегда — как в жизни. */
export function glUpgradeCost(from: GlPackageId, to: GlPackageId): number {
  return Math.max(0, glPackage(to).price - glPackage(from).price)
}

export function glUpgradeOptions(from: GlPackageId): GlPackage[] {
  const cur = glPackage(from)
  return GL_PACKAGES.filter((p) => p.price > cur.price)
}

/**
 * Шаг зарплаты: структура подросла, объём накопился, заморозка оттаяла.
 * Возвращает новое состояние и человеческую строчку для уведомления —
 * игрок должен понимать, ПОЧЕМУ доход изменился.
 */
export function glOnPayday(g: GlState): { next: GlState; note: string | null } {
  const before = glTotalIncome(g)
  const rankBefore = glRankFor(g.volume)

  const next: GlState = { ...g }
  next.volume += glStructureIncome(g)

  /*
   * 🔴 ПРОСАДКА КОНЧАЕТСЯ. Раньше `dipLeft` не убывал вообще: карточка
   * обещала «через несколько зарплат вернётся к своему», а человек до конца
   * партии недополучал пятую часть дохода по структуре. Соседний счётчик
   * заморозки уменьшался как надо — про этот просто забыли.
   * Жалоба Камиля 19.08: «после карточки „выбыл лидер" доход неправильный».
   */
  if (next.dipLeft > 0) {
    next.dipLeft -= 1
    if (next.dipLeft === 0) next.dipMul = 1
  }

  if (next.slowdownLeft > 0) {
    next.slowdownLeft -= 1
  } else {
    /*
     * Геометрия: доход растёт ПРОЦЕНТОМ от себя же. Чем больше структура, тем
     * больше людей приводит каждый месяц — потолка нет.
     */
    /*
     * 🔴 ТЕМП ЗАМЕДЛЯЕТСЯ ПО МЕРЕ РОСТА — но доход не упирается ни во что.
     * Чистая геометрия при живом темпе за три года выносила структуру в
     * миллионы в месяц, и партия теряла смысл. В жизни то же самое: маленькая
     * команда удваивается легко, большая — уже нет. Потолка дохода по-прежнему
     * НЕТ (поправка Камиля: у топов бывает и шестьдесят миллионов), тормозится
     * только скорость.
     */
    const damp = 1 + g.baseFlow / GL_GROWTH_SOFT
    const grow = (g.baseFlow * g.growthPct * g.luck) / 100 / damp
    next.baseFlow = Math.round((g.baseFlow + Math.max(100, grow)) / 100) * 100
  }

  const rankAfter = glRankFor(next.volume)
  const after = glTotalIncome(next)

  /*
   * Первый ранг — момент, когда структура начинает работать без тебя: до него
   * партнёрский бизнес в зачёт свободы не идёт вовсе. Это стоит объявить
   * отдельно, а не прятать в общую строку про ранг.
   */
  if (rankBefore.level === 0 && rankAfter.level > 0) {
    return {
      next,
      note: `Партнёрский бизнес заработал без вас: закрыт ранг «${rankAfter.name}», ${fmt(
        rankAfter.pension,
      )} в месяц идут сверх дохода структуры, а часть дохода теперь считается в свободу.`,
    }
  }
  if (rankAfter.level > rankBefore.level) {
    return {
      next,
      note: `Партнёрский бизнес: вы закрыли ранг «${rankAfter.name}». Это добавляет ${fmt(
        rankAfter.pension,
      )} в месяц сверх дохода структуры — и эти деньги остаются с вами, даже если команда возьмёт паузу.`,
    }
  }
  if (g.dipLeft > 0 && next.dipLeft === 0) {
    return {
      next,
      note: `Партнёрский бизнес: просадка кончилась — структура вернулась к своему, ${fmt(after)} в месяц.`,
    }
  }
  if (next.dipLeft > 0) {
    return {
      next,
      note:
        `Партнёрский бизнес: просадка держится ещё ${next.dipLeft} ${склонение(next.dipLeft)}. ` +
        `Сейчас ${fmt(after)} в месяц вместо обычного.`,
    }
  }
  if (next.slowdownLeft > 0) {
    return { next, note: `Партнёрский бизнес: приток новых людей пока стоит, доход не растёт.` }
  }
  if (after > before) {
    /*
     * 🔴 Показываем ПРИБАВКУ, а не только новую сумму. Камиль просил, чтобы по
     * ходу партии было видно, как растёт доход: «Ваш доход вырос ещё на
     * столько-то» — это и есть ощущение работающей структуры.
     */
    return {
      next,
      note: `Партнёрский бизнес: +${fmt(after - before)} к доходу — теперь ${fmt(after)} в месяц.`,
    }
  }
  return { next, note: null }
}

const fmt = (n: number) => `${n.toLocaleString('ru-RU')} ₽`

/** «1 зарплату», «2 зарплаты», «5 зарплат» — иначе строка читается как робот. */
function склонение(n: number): string {
  const д = n % 10
  const дд = n % 100
  if (дд >= 11 && дд <= 14) return 'зарплат'
  if (д === 1) return 'зарплату'
  if (д >= 2 && д <= 4) return 'зарплаты'
  return 'зарплат'
}
