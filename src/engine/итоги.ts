/**
 * В каком порядке стоят игроки в итогах партии — и почему.
 *
 * 🔴 ЗАЧЕМ. Список под заголовком «X побеждает!» сортировался ПО КАПИТАЛУ, а
 * победитель определяется по тому, кто первым купил мечту. Итог: победитель
 * мог стоять в собственном списке третьим, и за столом спорили, кто выиграл.
 * Правило Камиля (19.08): «кто первым купил мечту — первое место».
 *
 * Порядок: победители — в том порядке, в каком побеждали; дальше те, кто
 * вышел на Полосу свободы; дальше те, кто не вышел; дальше встал из-за стола;
 * последними — банкроты. Внутри группы — по капиталу. Рядом с каждым пишем
 * причину места, иначе список опять пришлось бы объяснять голосом.
 */
import { netWorth } from './ledger'
import type { Seat, Table } from './types'

export interface ИтогМеста {
  seat: Seat
  почему: string
}

function группа(s: Seat): number {
  if (s.won) return 0
  if (s.outOfGame) return 4
  if (s.внеГонки) return 3
  return s.track === 'fast' ? 1 : 2
}

export function итоговыйПорядок(t: Table): ИтогМеста[] {
  const порядок = [...t.seats].sort((a, b) => {
    const г = группа(a) - группа(b)
    if (г !== 0) return г
    if (a.won && b.won) {
      /*
       * 🔴 В старых партиях отметки хода нет — тогда первым идёт тот, кого
       * движок и так объявил победителем, остальные по капиталу.
       */
      const ха = a.победаНаХоду ?? (a.id === t.winnerId ? -1 : Infinity)
      const хб = b.победаНаХоду ?? (b.id === t.winnerId ? -1 : Infinity)
      if (ха !== хб) return ха - хб
    }
    return netWorth(b.ledger) - netWorth(a.ledger)
  })
  return порядок.map((s) => ({ seat: s, почему: причина(s, t) }))
}

function причина(s: Seat, t: Table): string {
  if (s.won) {
    const мечта = s.ledger.winReason !== 'cashflowGoal'
    if (s.id === t.winnerId) return мечта ? 'первым купил мечту' : 'первым дошёл до цели'
    return мечта ? 'тоже купил мечту' : 'тоже дошёл до цели'
  }
  if (s.outOfGame) return 'банкрот'
  if (s.внеГонки) return 'встал из-за стола'
  return s.track === 'fast' ? 'на втором круге' : 'не вышел на второй круг'
}
