/**
 * Рынки — страны, из которых собран стол.
 *
 * 🔴 ЗАЧЕМ. Просьба Камиля: «выбор рынков и стран перед началом» и отдельно —
 * «версия колоды без российских активов». Это одно и то же: колода одна, а
 * перед партией отмечают галочками, в каких странах играют. Двух колод не
 * заводим нарочно — разъедутся при первой же правке, как уже разъезжались
 * тексты и цифры.
 *
 * 🔴 РЫНОК ЖИВЁТ НА КАРТОЧКЕ, А НЕ ВЫВОДИТСЯ ИЗ КАТЕГОРИИ. Категория — это
 * ВИД актива, и она же несёт географию для новостей («квартиры в Дубае
 * подорожали»). Но совпадают они не всегда: гараж-бокс в Батуми лежит в
 * категории «машиноместа», где всё остальное российское. Выводили бы страну
 * из категории — в партии «без России» осталась бы Уфа, а Батуми пропал.
 *
 * 🔴 ЧТО НЕ ПРИВЯЗАНО К СТРАНЕ, ОСТАЁТСЯ ВСЕГДА: акции, партнёрский бизнес,
 * цифровое дело. У них поля `рынок` просто нет.
 */

export type Рынок = 'RU' | 'CIS' | 'TUR' | 'DXB' | 'SAU' | 'BALI'

export const РЫНКИ: { код: Рынок; имя: string; города: string }[] = [
  { код: 'RU', имя: 'Россия', города: 'Уфа, Казань, Москва, Питер, Дагестан, Сочи' },
  { код: 'CIS', имя: 'Соседние страны', города: 'Ташкент, Алматы, Батуми' },
  { код: 'TUR', имя: 'Турция', города: 'Стамбул, Анталия, Мерсин, Алания' },
  { код: 'DXB', имя: 'ОАЭ', города: 'Дубай' },
  { код: 'SAU', имя: 'Саудия', города: 'Мекка, Медина, Джидда, Эр-Рияд' },
  { код: 'BALI', имя: 'Индонезия', города: 'Бали: Чангу, Убуд, Семиньяк' },
]

export const ВСЕ_РЫНКИ: Рынок[] = РЫНКИ.map((р) => р.код)

export function известныйРынок(x: unknown): x is Рынок {
  return typeof x === 'string' && (ВСЕ_РЫНКИ as string[]).includes(x)
}

export function имяРынка(к: Рынок): string {
  return РЫНКИ.find((р) => р.код === к)?.имя ?? к
}

/**
 * Приводим выбор к порядку и убираем мусор.
 *
 * 🔴 Порядок обязателен: список едет в настройки стола, а настройки — в
 * сохранение и в сеть. `['RU','TUR']` и `['TUR','RU']` — один и тот же стол,
 * и колода после них обязана получиться байт в байт одинаковой, иначе журнал
 * ходов переиграется другими картами.
 */
export function нормализоватьРынки(x: unknown): Рынок[] | undefined {
  if (!Array.isArray(x)) return undefined
  const набор = new Set(x.filter(известныйРынок))
  if (!набор.size) return undefined
  const список = ВСЕ_РЫНКИ.filter((к) => набор.has(к))
  // Отмечены все — это и есть «без ограничений»: не тащим лишнее в сохранение.
  return список.length === ВСЕ_РЫНКИ.length ? undefined : список
}

/** Годится ли карточка при таком выборе стран. Без рынка — годится всегда. */
export function карточкаПодходит(
  c: { рынок?: string; kind?: string; category?: string },
  выбор: Рынок[] | undefined,
): boolean {
  if (!выбор) return true
  const м = c.рынок
  if (!м) return true
  return (выбор as string[]).includes(м)
}
