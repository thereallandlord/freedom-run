/**
 * Итоги партии: первое место у того, кто первым купил мечту.
 *
 * 🔴 Жалоба с игры 19.08: заголовок называл победителя, а список под ним
 * сортировался по капиталу — и победитель стоял в нём не первым.
 */
import { createTable } from './table'
import { итоговыйПорядок } from './итоги'
import type { Seat, Table } from './types'

const беды: string[] = []
const п = (что: string, ок: boolean, факт = '') => {
  if (!ок) беды.push(`${что}${факт ? ` — ${факт}` : ''}`)
}

function стол(): Table {
  return createTable({
    seed: 3,
    deckTheme: 'ru',
    seats: ['А', 'Б', 'В', 'Г', 'Д'].map((n, i) => ({
      id: `s${i}`,
      name: n,
      professionId: ['engineer', 'doctor', 'teacher', 'driver', 'engineer'][i],
      dreamSpace: [2, 13, 24, 39, 2][i],
    })),
  } as never)
}
function с(t: Table, i: number, правка: Partial<Seat>, наличные: number): Seat {
  return { ...t.seats[i], ...правка, ledger: { ...t.seats[i].ledger, cash: наличные } }
}

// 1. Победитель беднее всех — всё равно первый; второй победитель — вторым.
{
  const t0 = стол()
  const t: Table = {
    ...t0,
    winnerId: 's2',
    seats: [
      с(t0, 0, { won: true, победаНаХоду: 80 }, 90_000_000), // победил позже, но богаче всех
      с(t0, 1, { track: 'fast' }, 50_000_000),
      с(t0, 2, { won: true, победаНаХоду: 50 }, 100_000), // купил мечту первым, почти без денег
      с(t0, 3, { outOfGame: true }, 999_000_000), // банкрот с «капиталом» — всё равно последний
      с(t0, 4, { track: 'rat' }, 70_000_000), // богаче вышедшего на Полосу, но не вышел
    ],
  }
  const ид = итоговыйПорядок(t).map((x) => x.seat.id)
  п('первым стоит тот, кто первым купил мечту', ид[0] === 's2', ид.join(' '))
  п('вторым — второй победитель', ид[1] === 's0', ид.join(' '))
  п('вышедший на Полосу выше того, кто не вышел, даже если беднее', ид.indexOf('s1') < ид.indexOf('s4'), ид.join(' '))
  п('банкрот последним', ид[ид.length - 1] === 's3', ид.join(' '))
  const почему = итоговыйПорядок(t).map((x) => x.почему)
  п('у первого места написано, за что', почему[0] === 'первым купил мечту', почему[0])
  console.log('  ' + итоговыйПорядок(t).map((x, i) => `${i + 1}. ${x.seat.name} — ${x.почему}`).join(' · '))
}

// 2. Старая партия без отметок хода: первым идёт объявленный победитель.
{
  const t0 = стол()
  const t: Table = {
    ...t0,
    winnerId: 's1',
    seats: [с(t0, 0, { won: true }, 90_000_000), с(t0, 1, { won: true }, 100_000), с(t0, 2, {}, 1), с(t0, 3, {}, 1), с(t0, 4, {}, 1)],
  }
  const ид = итоговыйПорядок(t).map((x) => x.seat.id)
  п('в старой партии первым стоит объявленный победитель', ид[0] === 's1', ид.join(' '))
}

console.log(беды.length ? '\n❌ ИТОГИ:\n  ' + беды.join('\n  ') : '\n✅ ИТОГИ: первое место у того, кто первым купил мечту')
if (беды.length) (globalThis as { process?: { exit(n: number): void } }).process?.exit(1)
