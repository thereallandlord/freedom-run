/**
 * Событие обычного бизнеса — кафе, пункта выдачи, типографии.
 *
 * 🔴 ЗАЧЕМ ЭТО ЗАВЕДЕНО. В колодах двенадцать обычных бизнесов и всего ДВЕ
 * карточки, которые их задевают, — обе про выкуп. То есть человек покупал
 * кафе, и дальше с ним не происходило НИЧЕГО до конца партии. У партнёрского
 * бизнеса таких карточек семнадцать, и разница за столом видна сразу: один
 * путь живой, другой мёртвый.
 *
 * 🔴 СТАДИИ — как у партнёрского (решение Камиля: «первый год → встал на ноги
 * → вырос»). Внутри стадии карточка случайна, но порядок становится жизненным:
 * событие первого года не придёт сети из двух точек, а кража управляющего не
 * придёт тому, кто сам стоит за прилавком.
 */
export interface BizEventCard {
  kind: 'bizEvent'
  id: string
  title: string
  flavor: string
  /** На каких стадиях бизнеса выходит. Пусто — на любой. */
  stages?: number[]
  /** Каких видов бизнеса касается. Пусто — любого обычного. */
  categories?: string[]
  /**
   * Каких РЕМЁСЕЛ касается: «барбершоп», «автомойка», «ПВЗ». Пусто — любого в
   * этом рынке. 🔴 Ремесло и рынок — разные вещи: «услуги» это рынок, где
   * рядом стоят стрижки, мойка и типография, и новость про одно из них не
   * должна двигать доход двум другим.
   */
  ремесло?: string[]
  /** Доход бизнеса меняется НАВСЕГДА на столько процентов. */
  flowPct?: number
  /** Доход просел на время и вернётся сам. */
  dipPct?: number
  dipPaydays?: number
  /** Разовые деньги: минус — потратил, плюс — получил. */
  cash?: number
  /**
   * Цена решения: сколько стоит вложиться. Стоит поле — карточка становится
   * ВЫБОРОМ, а не сообщением.
   *
   * 🔴 ЗАЧЕМ. Из 77 событий дела 31 было чистым подарком: «рейтинг вырос,
   * доход +12%» прилетало само, человек читал и закрывал. Просьба Камиля —
   * «сделать карточки бизнесов интереснее», и интерес рождается решением, а
   * не текстом. Работает в обе стороны, по знаку `flowPct`:
   *   +% — вложился и получил прибавку навсегда; прошёл мимо — ничего;
   *   −% — вложился и удержал доход; прошёл мимо — просадка навсегда.
   * Денег не хватает — кнопка честно недоступна, и это тоже решение: копить
   * или держать наличные под такие случаи.
   */
  вложить?: number
  /**
   * Предложение управляющего: он согласен вести дело за ЭТУ долю потока
   * вместо обычной. 🔴 Это не подарок и не автоматическое действие — карточка
   * только открывает дверь, нанимать или остаться самому решает игрок.
   * Именно этот шаг и переводит бизнес из первого года во второй.
   */
  managerPct?: number
}

