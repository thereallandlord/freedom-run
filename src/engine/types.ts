/** Финансовое состояние одного игрока. */
export interface Ledger {
  playerName: string
  phase: LedgerPhase
  cash: number
  profession: Profession
  salary: number
  expenses: Expenses
  liabilities: Liabilities
  /** Питомцы (в оригинале — «дети»). Максимум 3. */
  /**
   * Дети. Каждый добавляет к расходам `perChildExpense` НАВСЕГДА.
   *
   * 🔴 Раньше поле называлось «питомцы» и клетка под него была снята с доски.
   * Решение Камиля 20.08: вернуть как в классической игре — ребёнок это
   * постоянный расход, а не разовая трата. Именно такие расходы и делают
   * партию длиннее.
   */
  children: number
  /**
   * Наивысший доход, который человек видел. По нему подтягиваются расходы.
   * Пусто — ещё ни одной зарплаты не было.
   */
  incomePeak?: number
  /**
   * Что произошло с партнёрским бизнесом за эту зарплату — человеческими
   * словами, для показа игроку.
   *
   * 🔴 Движок писал эти объяснения и ВЫБРАСЫВАЛ их: в разборе зарплаты
   * бралось только новое состояние. Отсюда живая жалоба «три раза за партию
   * никто не понял, откуда взялся доход» — игра знала ответ и молчала.
   * Копится за зарплату, стол забирает и показывает.
   */
  glNotes?: string[]
  /**
   * Сколько легло на счёт последней зарплатой — ровно то число, что панель
   * показывала ДО клетки.
   *
   * 🔴 Экраны считали чек заново по кошельку ПОСЛЕ зарплаты, а там уже подрос
   * партнёрский бизнес и подтянулись расходы: окно «Пришли деньги» называло
   * доход следующего месяца. Теперь сумму говорит тот, кто её заплатил.
   */
  lastPaycheck?: number
  stocks: StockLot[]
  realEstate: RealEstateAsset[]
  businesses: BusinessAsset[]
  charityTurnsLeft: number
  /** Сколько зарплат получено — по нему наступает срок закята. */
  paydays: number
  /**
   * На каком месяце человек перешёл рубеж свободы — доход стал вдвое выше
   * расходов.
   *
   * 🔴 РУБЕЖ, А НЕ ПОБЕДА. Победа на втором круге одна: купить свою мечту.
   * Поле нужно затем, чтобы отметить момент вслух и показать его в панели —
   * иначе главное достижение партии проходит незамеченным.
   */
  свободенС?: number
  /** Сколько зарплат ещё идёт беспроцентный период по кредиту. */
  ribaGraceLeft?: number
  /** Подряд отказов от хотелок — по ним наступает выгорание. */
  wantsRefused?: number
  /**
   * Долг с надбавкой, в котором игрок участвует ЛЮБОЙ стороной.
   * 🔴 Считается в риск наравне с банковским кредитом: дал под процент —
   * неприятности приходят и к тебе. Риба портит сделку с обеих сторон.
   */
  ribaExposure?: number
  /**
   * Второй паспорт. Не инвестиция: потока не даёт вообще, зато снимает целый
   * класс бед — «платёж не прошёл», «счёт не открыть», «сервис недоступен».
   * Условие настоящее: Турция даёт гражданство за 400 тысяч долларов в
   * недвижимости, Карибы — за взнос без всякой недвижимости.
   */
  citizenship?: string
  fastTrack?: FastTrackState
  winReason?: 'dream' | 'cashflowGoal'
}

