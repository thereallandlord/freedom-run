export interface RealEstateAsset {
  id: string
  name: string
  cost: number
  downPayment: number
  mortgage: number
  cashFlow: number
  category: string
  investorShare?: number
  /** Платёж по рассрочке, уже вычтенный из cashFlow. Ноль — куплено налом. */
  installmentMonthly?: number
  /**
   * ПРОСТОЙ: квартира временно не приносит или приносит меньше.
   *
   * 🔴 ЗАЧЕМ. Просьба Камиля с игры: «добавь карточки, чтобы можно было
   * потерять — арендатор съехал, и ты больше не зарабатываешь с этой
   * квартиры». Карточки бед у недвижимости были, но все до одной отнимали
   * РАЗОВЫЕ деньги, а доход капал как ни в чём не бывало: съехал арендатор —
   * и ничего не изменилось. Поднимать доход карточки умели (+8%, +12%),
   * опускать — ни одна.
   *
   * Механика та же, что у дел: множитель и срок в зарплатах. Считает её общий
   * `ownShareAt`, поэтому доход, зачёт свободы и панель сходятся сами.
   */
  dipMul?: number
  dipLeft?: number
  /**
   * 🔴 РЫНОЧНАЯ СТОИМОСТЬ объекта — то, за сколько он стоит НА РЫНКЕ, без
   * наценки за рассрочку. У купленного в рассрочку `cost` — это цена с
   * наценкой (6 млн превращаются в 7,5 млн), и выкуп «за 140% стоимости»
   * считался от неё: игрок получал вдвое больше вложенного и рынок работал
   * печатным станком. Продажа считается от этой величины.
   */
  value?: number
  /**
   * Сколько СВОИХ денег реально ушло на вход.
   *
   * 🔴 Отдельным полем, потому что у купленного вдвоём `downPayment` равен
   * нулю: взнос там списывается двумя переводами ДО сборки актива, иначе
   * деньги сняли бы дважды. Панель из-за этого печатала «Вложено своих 0 ₽»
   * человеку, который только что заплатил двадцать тысяч.
   */
  paidIn?: number
  /** Кто соинвестор, если актив куплен в долях. */
  partnerId?: string
  /**
   * Вошёл в чужую находку на условиях доли с прибыли: кому и сколько процентов
   * отдать при продаже. Ровно как у бумаг — отщипывается только с ПРИБЫЛИ.
   */
  profitShareTo?: string
  profitSharePct?: number
}

export interface BusinessAsset {
  id: string
  name: string
  cost: number
  downPayment: number
  liability: number
  cashFlow: number
  category: string
  /** Доля инвестора в потоке и выручке (0–1). Хозяин получает (1 − share). */
  investorShare?: number
  /** Партнёрский бизнес: прирост потока на каждый день зарплаты, до потолка. */
  growthPerPayday?: number
  growthCap?: number
  /**
   * Нанят управляющий: какую долю потока он забирает.
   * 🔴 Пока управляющего нет, бизнес приносит ДЕНЬГИ, но не приближает свободу:
   * ты в нём работаешь сам. Наняли — часть дохода уходит ему, зато остаток
   * идёт в зачёт выхода из круга. Это и есть переход от самозанятости
   * к владению, и ради него игра и затевалась.
   */
  managerPct?: number
  /**
   * Временная просадка дохода после события: множитель и сколько зарплат он
   * ещё держится. 🔴 Именно ВРЕМЕННАЯ — она уходит сама, без действий игрока.
   * Постоянные изменения пишутся прямо в cashFlow, здесь их держать нельзя:
   * иначе после отсчёта доход вернулся бы к старому.
   */
  dipMul?: number
  dipLeft?: number
  /**
   * Партнёрский бизнес GreenLeaf. Если поле есть — доход этого актива считает
   * НЕ cashFlow, а движок GreenLeaf: пакет-множитель, растущая структура,
   * пенсия за ранг, просадки. Правила живут в engine/greenleaf.ts.
   */
  gl?: import('./greenleaf').GlState
  installmentMonthly?: number
  partnerId?: string
  /**
   * Вошёл в чужую находку на условиях доли с прибыли: кому и сколько процентов
   * отдать при продаже. Ровно как у бумаг — отщипывается только с ПРИБЫЛИ.
   */
  profitShareTo?: string
  profitSharePct?: number
  /** Рыночная стоимость без наценки за рассрочку — от неё считается выкуп. */
  value?: number  /**
   * Сколько СВОИХ денег реально ушло на вход. См. пояснение у недвижимости:
   * у купленного вдвоём `downPayment` равен нулю, и панель врала нулём.
   */
  paidIn?: number

}

