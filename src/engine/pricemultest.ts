/**
 * Кнопка быстрой продажи обязана считать ТУ ЖЕ цену, что заплатит движок.
 *
 * 🔴 Жалоба Камиля: «машиноместо подорожало на 25% — а что толку?». Толк был:
 * движок платил с учётом подорожания, а кнопка считала с множителем 1 и
 * обещала меньше. Разрыв виден только в деньгах на счету.
 */
import { sellOfferQuote, СКИДКА_ЗА_СКОРОСТЬ } from './table'

const беды: string[] = []
const объект = { cost: 2_000_000, value: 2_000_000, downPayment: 400_000, paidIn: 400_000 }
console.log('множитель  кнопка (было)  кнопка (стало)  движок')
for (const мул of [1, 1.25, 1.4, 0.8]) {
  const было = sellOfferQuote(объект, 0, СКИДКА_ЗА_СКОРОСТЬ, 1).price
  const стало = sellOfferQuote(объект, 0, СКИДКА_ЗА_СКОРОСТЬ, мул).price
  const движок = sellOfferQuote(объект, 0, СКИДКА_ЗА_СКОРОСТЬ, мул).price
  console.log(
    `${String(мул).padStart(9)} ${String(было).padStart(13)} ${String(стало).padStart(15)} ${String(движок).padStart(7)}`,
  )
  if (стало !== движок) беды.push(`при множителе ${мул} кнопка и движок расходятся`)
  if (мул !== 1 && стало === было) беды.push(`при множителе ${мул} цена не изменилась — рынок не учтён`)
}
for (const б of беды) console.log('  ❌', б)
console.log(беды.length ? '\n❌ КНОПКА ОБЕЩАЕТ НЕ ТО, ЧТО ПЛАТИТ ДВИЖОК' : '\n✅ КНОПКА И ДВИЖОК СЧИТАЮТ ОДИНАКОВО')
if (беды.length) (globalThis as { process?: { exitCode?: number } }).process!.exitCode = 1
