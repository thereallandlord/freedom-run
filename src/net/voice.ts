/**
 * Голос прямо в игре: слышим друг друга без Zoom и без второго приложения.
 *
 * 🔴 ПОЧЕМУ БЕЗ СТОРОННЕГО СЕРВИСА. Звук идёт НАПРЯМУЮ между браузерами
 * (WebRTC, схема «каждый с каждым»). Сервер нужен только чтобы участники нашли
 * друг друга — для этого берём тот же Supabase, на котором уже держатся
 * комнаты, и заводим ОТДЕЛЬНЫЙ канал. Игровой журнал голос не трогает вовсе:
 * перепутать сигнальное сообщение с ходом невозможно, они ездят по разным
 * каналам.
 *
 * 🔴 ЧЕГО ЭТА СХЕМА СТОИТ. Каждый шлёт свой звук каждому: на десятерых это
 * девять исходящих дорожек с человека. Для звука это терпимо (Opus ~30 кбит/с,
 * то есть около 300 кбит/с вверх), для видео было бы нельзя. Потолок мы честно
 * показываем в интерфейсе, а не делаем вид, что схема бесконечная.
 *
 * 🔴 ЧЕГО НЕ УМЕЕМ. Нет своего TURN-сервера: если у кого-то жёсткий NAT
 * (корпоративная сеть, редкие мобильные операторы), соединение может не
 * подняться — у него не будет слышно, у остальных всё в порядке. Это видно в
 * списке участников, а не молчаливо.
 */
import { getSupabase } from './supabase'
import type { RealtimeChannel } from '@supabase/supabase-js'

function env(имя: string): string {
  const v = (import.meta as unknown as { env?: Record<string, string | undefined> }).env
  return (v?.[имя] ?? '').trim()
}

/**
 * 🔴 ОДНОГО STUN МАЛО — НУЖЕН РЕТРАНСЛЯТОР.
 *
 * STUN лишь подсказывает браузеру его внешний адрес; дальше собеседники
 * пробуют соединиться НАПРЯМУЮ. Дома и в офисе это обычно получается, а вот у
 * мобильных операторов и в части корпоративных сетей прямой дороги нет вовсе —
 * и звук не доходит НИКУДА, при том что микрофон честно включён и своя полоска
 * громкости шевелится. Ровно это и случилось на живой игре: я проверял двух
 * участников на ОДНОЙ машине, где прямая дорога есть всегда, и этой беды не
 * увидел.
 *
 * Лечится сервером-ретранслятором (TURN): он принимает звук и передаёт дальше,
 * когда напрямую нельзя. Адрес и ключи берём из переменных окружения — без них
 * голос работает как раньше (напрямую), и интерфейс об этом честно
 * предупреждает, а не притворяется.
 */
const TURN_URL = env('VITE_TURN_URL')
const TURN_USER = env('VITE_TURN_USER')
const TURN_PASS = env('VITE_TURN_PASS')

export function ретрансляторНастроен(): boolean {
  return !!TURN_URL && !!TURN_USER && !!TURN_PASS
}

const ICE: RTCIceServer[] = [
  { urls: ['stun:stun.l.google.com:19302', 'stun:global.stun.twilio.com:3478'] },
  ...(ретрансляторНастроен()
    ? [{ urls: TURN_URL.split(',').map((s) => s.trim()).filter(Boolean), username: TURN_USER, credential: TURN_PASS }]
    : []),
]

export type СостояниеУчастника = 'соединяемся' | 'слышно' | 'не вышло'

/** Что именно происходит с голосом — чтобы не гадать по молчанию. */
export type ДиагнозГолоса =
  | 'выключен'
  | 'ждём других'
  | 'соединяемся'
  | 'слышно'
  | 'нет дороги'

export interface УчастникГолоса {
  id: string
  имя: string
  состояние: СостояниеУчастника
  /** Говорит прямо сейчас — для подсветки в списке. */
  говорит: boolean
  /** Громкость 0..1 — чтобы видеть, что звук ИДЁТ, а не гадать. */
  уровень: number
}

export interface Голос {
  включить(): Promise<void>
  выключить(): void
  /** Свой микрофон: выключенный — нас не слышно, но мы слышим всех. */
  микрофон(вкл: boolean): void
  состояние(): {
    включён: boolean
    микрофонВкл: boolean
    участники: УчастникГолоса[]
    /** Своя громкость 0..1: единственный способ проверить, что микрофон живой. */
    мойУровень: number
    /** Одним словом, что сейчас с голосом. */
    диагноз: ДиагнозГолоса
    /** Есть ли сервер-ретранслятор — от этого зависит совет при неудаче. */
    ретрансляторЕсть: boolean
  }
  /** Подписка на изменения — чтобы интерфейс перерисовывался. */
  наИзменение(cb: () => void): () => void
  ошибка(): string | null
}

type Сигнал =
  | { t: 'привет'; from: string; имя: string }
  | { t: 'оффер'; from: string; to: string; имя: string; sdp: string }
  | { t: 'ответ'; from: string; to: string; sdp: string }
  | { t: 'лёд'; from: string; to: string; ice: RTCIceCandidateInit }
  | { t: 'пока'; from: string }

/** Голос доступен только когда есть чем сигналить и что записывать. */
export function голосДоступен(): boolean {
  return (
    !!getSupabase() &&
    typeof navigator !== 'undefined' &&
    !!navigator.mediaDevices?.getUserMedia &&
    typeof RTCPeerConnection !== 'undefined'
  )
}

export function создатьГолос(комната: string, я: { id: string; имя: string }): Голос {
  type Связь = {
    pc: RTCPeerConnection
    audio: HTMLAudioElement
    имя: string
    состояние: СостояниеУчастника
    говорит: boolean
    уровень: number
    анализ?: { stop: () => void }
    /*
     * 🔴 ЛЁД, ПРИШЕДШИЙ РАНЬШЕ ОФФЕРА, НАДО ПРИДЕРЖАТЬ, А НЕ ВЫБРОСИТЬ.
     * addIceCandidate до setRemoteDescription бросает исключение; оно у нас
     * гасилось пустым catch — и адреса молча пропадали. На быстрой сети
     * кандидаты обгоняют оффер регулярно, и связь оставалась без путей.
     */
    лёдОчередь: RTCIceCandidateInit[]
    звонил: boolean
  }
  const связи = new Map<string, Связь>()
  let канал: RealtimeChannel | null = null
  let мой: MediaStream | null = null
  let свойАнализ: { stop: () => void } | null = null
  let мойУровень = 0
  let включён = false
  let микВкл = true
  let ошибкаТекст: string | null = null
  const слушатели = new Set<() => void>()
  const изменилось = () => {
    for (const cb of слушатели) cb()
  }

  const шлём = (s: Сигнал) => {
    канал?.send({ type: 'broadcast', event: 'voice', payload: s })
  }

  /**
   * 🔴 КТО КОМУ ЗВОНИТ, РЕШАЕТ СРАВНЕНИЕ КЛЮЧЕЙ, А НЕ «КТО ПЕРВЫЙ УСПЕЛ».
   * Иначе двое одновременно шлют оффер друг другу, и соединение не встаёт
   * (классическая «встречка»). Звонит тот, чей ключ меньше.
   */
  const язвоню = (кому: string) => я.id < кому

  function создатьСвязь(id: string, имя: string): Связь {
    const pc = new RTCPeerConnection({ iceServers: ICE })
    /*
     * 🔴 Элемент звука ДОБАВЛЯЕМ В СТРАНИЦУ. Оторванный от документа он играет
     * не везде: Safari на айфоне такой звук молча глушит, а на экране всё
     * выглядит подключённым. Прячем стилем, а не отсутствием в документе.
     */
    const audio = document.createElement('audio')
    audio.autoplay = true
    audio.setAttribute('playsinline', '')
    audio.style.display = 'none'
    document.body.appendChild(audio)
    const связь: Связь = { pc, audio, имя, состояние: 'соединяемся', говорит: false, уровень: 0, лёдОчередь: [], звонил: false }

    if (мой) for (const t of мой.getTracks()) pc.addTrack(t, мой)

    pc.onicecandidate = (e) => {
      if (e.candidate) шлём({ t: 'лёд', from: я.id, to: id, ice: e.candidate.toJSON() })
    }
    pc.ontrack = (e) => {
      audio.srcObject = e.streams[0]
      void audio.play().catch(() => {})
      связь.анализ = следитьЗаГолосом(e.streams[0], (ур) => {
        связь.уровень = ур
        const гов = ур > 0.08
        if (связь.говорит !== гов) {
          связь.говорит = гов
          изменилось()
        }
      })
    }
    pc.onconnectionstatechange = () => {
      const s = pc.connectionState
      связь.состояние = s === 'connected' ? 'слышно' : s === 'failed' || s === 'closed' ? 'не вышло' : 'соединяемся'
      изменилось()
    }
    связи.set(id, связь)
    return связь
  }

  async function позвонить(id: string, имя: string) {
    const связь = связи.get(id) ?? создатьСвязь(id, имя)
    // Звоним один раз: повторный оффер по живой связи ломает уже собранную.
    if (связь.звонил) return
    связь.звонил = true
    const offer = await связь.pc.createOffer({ offerToReceiveAudio: true })
    await связь.pc.setLocalDescription(offer)
    шлём({ t: 'оффер', from: я.id, to: id, имя: я.имя, sdp: offer.sdp ?? '' })
  }

  /*
   * 🔴 СИГНАЛЫ РАЗБИРАЕМ СТРОГО ПО ОЧЕРЕДИ. Обработчик асинхронный, а сообщения
   * приходят пачкой: два разбора одной связи наперегонки роняют согласование
   * (оффер и ответ применяются вперемешку). Цепочка обещаний стоит дёшево и
   * снимает целый класс плавающих отказов.
   */
  let очередьСигналов: Promise<void> = Promise.resolve()
  function приняли(s: Сигнал): Promise<void> {
    очередьСигналов = очередьСигналов.then(() => обработать(s)).catch((e) => {
      console.error('[голос] сигнал не разобран:', e)
    })
    return очередьСигналов
  }

  async function обработать(s: Сигнал) {
    if (s.t === 'привет') {
      if (s.from === я.id) return
      /*
       * 🔴 ЗДОРОВАЕМСЯ В ОТВЕТ ТОЛЬКО С НЕЗНАКОМЫМ.
       *
       * Раньше отвечали на КАЖДОЕ «привет» — и двое здоровались бесконечно:
       * моё «привет» будило его ответ, его ответ будил мой. Канал один на всех,
       * поэтому на десятерых это лавина сообщений, которая забивает связь и
       * заодно гонит бесконечную перепись оффера. Голос при этом включается,
       * микрофон горит, а до собеседника не доходит ничего.
       *
       * Со знакомым просто освежаем имя и молчим — обмен затухает после
       * трёх сообщений: его «привет» → мой ответ → его молчание.
       */
      const новичок = !связи.has(s.from)
      if (новичок) создатьСвязь(s.from, s.имя)
      else связи.get(s.from)!.имя = s.имя
      изменилось()
      if (!новичок) return
      шлём({ t: 'привет', from: я.id, имя: я.имя })
      if (язвоню(s.from)) await позвонить(s.from, s.имя)
      return
    }
    if (s.t === 'пока') {
      закрыть(s.from)
      return
    }
    if (s.to !== я.id) return
    if (s.t === 'оффер') {
      const связь = связи.get(s.from) ?? создатьСвязь(s.from, s.имя)
      связь.имя = s.имя
      await связь.pc.setRemoteDescription({ type: 'offer', sdp: s.sdp })
      await разобратьЛёд(связь)
      const ans = await связь.pc.createAnswer()
      await связь.pc.setLocalDescription(ans)
      шлём({ t: 'ответ', from: я.id, to: s.from, sdp: ans.sdp ?? '' })
      изменилось()
      return
    }
    if (s.t === 'ответ') {
      const связь = связи.get(s.from)
      /*
       * Ждём ответ, только пока сами держим оффер. Прежняя проверка «ещё нет
       * удалённой стороны» после первого же соединения запирала связь навсегда.
       */
      if (!связь || связь.pc.signalingState !== 'have-local-offer') return
      await связь.pc.setRemoteDescription({ type: 'answer', sdp: s.sdp })
      await разобратьЛёд(связь)
      return
    }
    if (s.t === 'лёд') {
      const связь = связи.get(s.from)
      if (!связь) return
      if (!связь.pc.remoteDescription) {
        связь.лёдОчередь.push(s.ice)
        return
      }
      await связь.pc.addIceCandidate(s.ice).catch((e) => console.warn('[голос] лёд не принят:', e))
    }
  }

  /** Отдаём придержанные адреса, как только появилась удалённая сторона. */
  async function разобратьЛёд(связь: Связь) {
    const очередь = связь.лёдОчередь.splice(0)
    for (const ice of очередь)
      await связь.pc.addIceCandidate(ice).catch((e) => console.warn('[голос] лёд не принят:', e))
  }

  function закрыть(id: string) {
    const связь = связи.get(id)
    if (!связь) return
    связь.анализ?.stop()
    связь.pc.close()
    связь.audio.srcObject = null
    связь.audio.remove()
    связи.delete(id)
    изменилось()
  }

  return {
    async включить() {
      if (включён) return
      ошибкаТекст = null
      const sb = getSupabase()
      if (!sb) {
        ошибкаТекст = 'Голос работает только в онлайн-комнате.'
        изменилось()
        return
      }
      try {
        /*
         * 🔴 Просим ТОЛЬКО микрофон и просим его ДО подключения к каналу:
         * браузер обязан спросить разрешение по нажатию, а если сначала уйти
         * в сеть, айфон успевает потерять «жест пользователя» и молча
         * отказывает.
         */
        мой = await navigator.mediaDevices.getUserMedia({
          audio: { echoCancellation: true, noiseSuppression: true, autoGainControl: true },
          video: false,
        })
      } catch {
        ошибкаТекст = 'Не дали доступ к микрофону. Разрешите его в настройках браузера.'
        изменилось()
        return
      }
      // Нажатие уже случилось — самое время разбудить звук, пока жест «живой».
      звук()
      /*
       * 🔴 СВОЙ УРОВЕНЬ МЕРЯЕМ ТОЖЕ. Без него человек не может проверить
       * собственный микрофон: он говорит, а слышат его или нет — знают только
       * другие. Полоска своей громкости отвечает на это сразу и без спроса.
       */
      свойАнализ = следитьЗаГолосом(мой, (ур) => {
        мойУровень = ур
      })
      включён = true
      микВкл = true
      /*
       * 🔴 ОДНО ИМЯ КАНАЛА — ОДИН КАНАЛ НА КЛИЕНТА.
       *
       * Второй канал с тем же именем у Supabase просто не поднимается: подписка
       * висит вечно, ошибки нет, голос молчит. А второй берётся легко: в
       * разработке React монтирует всё дважды, и панель успевала создать две
       * связи. Поймано живой проверкой — связь не вставала НИ РАЗУ, при том что
       * тот же канал вручную работал.
       */
      const имяКанала = `voice:${комната}`
      for (const c of sb.getChannels()) {
        if (c.topic === `realtime:${имяКанала}` || c.topic === имяКанала) void sb.removeChannel(c)
      }
      канал = sb.channel(имяКанала, { config: { broadcast: { self: false } } })
      канал.on('broadcast', { event: 'voice' }, (m) => {
        /*
         * 🔴 Ловим ошибку ЗДЕСЬ. Обработчик асинхронный: без этого любая
         * осечка в разборе сигнала уходила бы в пустоту, и голос просто не
         * поднимался бы — молча, без единой строки в консоли. Именно так я и
         * потерял час на живой проверке.
         */
        приняли(m.payload as Сигнал).catch((e) => console.error('[голос] сигнал не разобран:', e))
      })
      канал.subscribe((st) => {
        if (st === 'SUBSCRIBED') шлём({ t: 'привет', from: я.id, имя: я.имя })
      })
      изменилось()
    },
    выключить() {
      if (!включён) return
      шлём({ t: 'пока', from: я.id })
      for (const id of [...связи.keys()]) закрыть(id)
      // Освобождаем ИМЯ канала, а не просто отписываемся: иначе повторное
      // включение упрётся в занятое имя и молча не поднимется.
      if (канал) void getSupabase()?.removeChannel(канал)
      канал = null
      свойАнализ?.stop()
      свойАнализ = null
      мойУровень = 0
      мой?.getTracks().forEach((t) => t.stop())
      мой = null
      включён = false
      изменилось()
    },
    микрофон(вкл) {
      микВкл = вкл
      мой?.getAudioTracks().forEach((t) => (t.enabled = вкл))
      изменилось()
    },
    состояние() {
      return {
        включён,
        микрофонВкл: микВкл,
        участники: [...связи.entries()].map(([id, с]) => ({
          id,
          имя: с.имя,
          состояние: с.состояние,
          говорит: с.говорит,
          уровень: с.уровень,
        })),
        мойУровень: микВкл ? мойУровень : 0,
        диагноз: !включён
          ? 'выключен'
          : связи.size === 0
            ? 'ждём других'
            : [...связи.values()].some((с) => с.состояние === 'слышно')
              ? 'слышно'
              : [...связи.values()].every((с) => с.состояние === 'не вышло')
                ? 'нет дороги'
                : 'соединяемся',
        ретрансляторЕсть: ретрансляторНастроен(),
      }
    },
    наИзменение(cb) {
      слушатели.add(cb)
      return () => слушатели.delete(cb)
    },
    ошибка() {
      return ошибкаТекст
    },
  }
}

/**
 * 🔴 ОДИН ЗВУКОВОЙ КОНТЕКСТ НА ВСЕХ, И ЕГО НАДО БУДИТЬ.
 *
 * Создавали по контексту на собеседника — на десятерых это десять звуковых
 * движков впустую. Хуже другое: контекст, созданный без нажатия, стартует
 * СПЯЩИМ, и замер громкости честно возвращает нули — подсветка «говорит» не
 * загоралась никогда. Поймано живой проверкой: связь стояла, а огонёк молчал.
 */
let общийКонтекст: AudioContext | null = null
function звук(): AudioContext {
  const Ctx =
    window.AudioContext ??
    (window as unknown as { webkitAudioContext: typeof AudioContext }).webkitAudioContext
  if (!общийКонтекст) общийКонтекст = new Ctx()
  if (общийКонтекст.state === 'suspended') void общийКонтекст.resume().catch(() => {})
  return общийКонтекст
}

/**
 * Кто сейчас говорит — по громкости дорожки.
 * Нужен только для подсветки: без него голос работает, но не видно, кто из
 * десяти сейчас в эфире, и все начинают говорить разом.
 */
function следитьЗаГолосом(stream: MediaStream, cb: (уровень: number) => void) {
  const ctx = звук()
  const src = ctx.createMediaStreamSource(stream)
  const an = ctx.createAnalyser()
  an.fftSize = 1024
  src.connect(an)
  const buf = new Uint8Array(an.fftSize)
  let живой = true
  let сглаж = 0
  /*
   * 🔴 ГРОМКОСТЬ СЧИТАЕМ ПО ВОЛНЕ, А НЕ ПО СПЕКТРУ. Среднее по частотным
   * корзинам занижает всё, что звучит узко: чистый тон размазывался в 6% на
   * полоске, хотя звук шёл в полный голос. Обычная мера громкости — сила
   * колебания (RMS): она одинаково честна и к тону, и к речи.
   */
  const тик = () => {
    if (!живой) return
    an.getByteTimeDomainData(buf)
    let сумма = 0
    for (const v of buf) {
      const d = (v - 128) / 128
      сумма += d * d
    }
    const rms = Math.sqrt(сумма / buf.length)
    // Плавно поднимаем и плавно опускаем: иначе полоска дрожит на каждом слоге.
    сглаж = Math.max(rms, сглаж * 0.75)
    cb(Math.min(1, сглаж * 3.2))
    setTimeout(тик, 100)
  }
  тик()
  return {
    ctx,
    stop: () => {
      живой = false
      // Контекст общий — закрывать его нельзя, отключаем только свой источник.
      try {
        src.disconnect()
      } catch {
        /* уже отключён */
      }
    },
  }
}
