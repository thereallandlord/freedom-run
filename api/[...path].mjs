/**
 * Приёмник запросов для Vercel.
 *
 * 🔴 Зачем вторая площадка. Railway из России без VPN не открывается — режут
 * не наш домен, а всю их пограничную сеть, так что сменой домена это не
 * лечится. Vercel из России открывается, поэтому игра живёт на двух адресах
 * сразу: кому-то откроется один, кому-то другой.
 *
 * 🔴 ИМЯ ФАЙЛА — ЧАСТЬ РАБОТЫ. С необязательным перехватом `[[...path]]`
 * Vercel ловил только два сегмента: `/api/rules` отвечал, а `/api/rules/can-edit`
 * и `/api/games/<id>/debrief` отдавали чужой 404 — при том что обработчик их
 * знает. Обязательный `[...path]` ловит любую глубину.
 *
 * 🔴 Своей логики здесь НЕТ намеренно. Вся она — в server/index.mjs, и оба
 * хостинга зовут один и тот же обработчик. Скопируй код сюда — и две копии
 * игры начнут вести себя по-разному, а понять почему будет почти невозможно.
 */
import { handler } from '../server/index.mjs'

export const config = {
  // Разбор партии ходит к модели и думает долго. Потолок бесплатного тарифа
  // Vercel — 60 секунд; по умолчанию там 10, чего разбору не хватает.
  maxDuration: 60,
}

export default function (req, res) {
  /*
   * 🔴 Возврат от Google приходит на /auth-back, но у Vercel функции живут
   * только под /api/*, поэтому в vercel.json стоит переброс. Возвращаем адрес
   * обратно, чтобы обработчик видел ровно тот же путь, что и на своём сервере,
   * и его не пришлось учить знать, где он запущен.
   */
  if (req.url && req.url.startsWith('/api/auth-back')) {
    req.url = req.url.replace('/api/auth-back', '/auth-back')
  }
  return handler(req, res)
}
